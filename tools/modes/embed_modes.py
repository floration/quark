#!/usr/bin/env python3
"""Embed tools/modes/*.qlogic in the game: writes <out>/default_modes.h (kDefaultModeTexts: name + text, byte arrays).

Usage: embed_modes.py <out dir> <tools/modes dir>. common.qlogic and one file per mode (vs bomb race koth payload ffa
npayload duel arena tourney hide tag points surf); a missing one fails the build."""
import os
import sys

NAMES = ['common', 'vs', 'bomb', 'race', 'koth', 'payload', 'ffa', 'npayload', 'duel', 'arena', 'tourney', 'hide', 'tag', 'points', 'surf']

out_dir, src_dir = sys.argv[1], sys.argv[2]
parts = ['// Generated by tools/modes/embed_modes.py from tools/modes/*.qlogic: do not edit.\n', '#pragma once\n']
for name in NAMES:
    path = os.path.join(src_dir, name + '.qlogic')
    if not os.path.exists(path):
        sys.exit('embed_modes.py: missing ' + path)
    data = open(path, 'rb').read().replace(b'\r\n', b'\n')
    rows = ['    ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',' for i in range(0, len(data), 24)]
    parts.append('static const char kMode_%s[] = {\n%s\n    0x00\n};\n' % (name, '\n'.join(rows)))
parts.append('struct DefaultModeText { const char* name; const char* text; };\n')
parts.append('static const DefaultModeText kDefaultModeTexts[] = {\n' + ''.join('    {"%s", kMode_%s},\n' % (n, n) for n in NAMES) + '};\n')
text = ''.join(parts)
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, 'default_modes.h')
if not os.path.exists(path) or open(path).read() != text:   # (unchanged: keep the timestamp, no rebuild)
    with open(path, 'w') as f:
        f.write(text)
