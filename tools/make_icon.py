#!/usr/bin/env python3
"""Draws the quark icon: a Rubik ExtraBold 'Q' split into team (cyan) and enemy (red) colors,
black outline, on a dark rounded tile. Needs Pillow (pip install pillow).
Writes assets/quark.ico (16-256 px), assets/quark.png (256 px), src/launcher/icon_data.h (embedded PNG)
and site/icon.png (website favicon).
The owner's icon wins (docs/ASSETS.md): with assets/overrides/images/icon.<png|jpg|jpeg>, every size is made from
that picture instead of the drawn Q, and assets/quark.icon-source records its sha256 (quark_tests checks the shipped
icon was made from the current override: run this again after changing it)."""
import hashlib, io, os, struct, sys
from PIL import Image, ImageDraw, ImageFont, ImageFilter, ImageChops

root = sys.argv[1] if len(sys.argv) > 1 else "."
CY, RD, BG = (64, 217, 255), (255, 77, 64), (20, 24, 32)
FONT = os.path.join(root, "assets/fonts/Rubik.ttf")

def font(size):
    f = ImageFont.truetype(FONT, size)
    try: f.set_variation_by_axes([800])  # ExtraBold
    except Exception: pass
    return f

def draw(S=1024):
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    m = int(S * 0.03)
    d.rounded_rectangle([m, m, S - m, S - m], radius=int(S * 0.2), fill=(0, 0, 0, 255))
    o = m + int(S * 0.03)
    d.rounded_rectangle([o, o, S - o, S - o], radius=int(S * 0.18), fill=BG + (255,))
    f = font(int(S * 0.7))
    l, t, r, b = d.textbbox((0, 0), "Q", font=f)
    f = font(int(S * 0.7 * (S * 0.64) / max(r - l, b - t)))
    l, t, r, b = d.textbbox((0, 0), "Q", font=f)
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).text(((S - (r - l)) / 2 - l, (S - (b - t)) / 2 - t), "Q", font=f, fill=255)
    img.paste((0, 0, 0, 255), (0, 0), mask.filter(ImageFilter.MaxFilter(2 * int(S * 0.018) + 1)))
    split = Image.new("RGBA", (S, S), CY + (255,))
    ImageDraw.Draw(split).polygon([(S * 0.58, 0), (S, 0), (S, S), (S * 0.42, S)], fill=RD + (255,))
    img.paste(split, (0, 0), mask)
    seam = Image.new("L", (S, S), 0)
    ImageDraw.Draw(seam).line([(S * 0.58, 0), (S * 0.42, S)], fill=255, width=int(S * 0.012))
    img.paste((0, 0, 0, 255), (0, 0), ImageChops.multiply(seam, mask))
    return img

override = next((os.path.join(root, "assets/overrides/images/icon" + e) for e in (".png", ".jpg", ".jpeg")
                 if os.path.isfile(os.path.join(root, "assets/overrides/images/icon" + e))), None)
marker = os.path.join(root, "assets/quark.icon-source")
if override:   # the owner's picture, centred on a square transparent canvas
    src = Image.open(override).convert("RGBA")
    S = 1024
    k = S / max(src.size)
    src = src.resize((max(1, round(src.size[0] * k)), max(1, round(src.size[1] * k))), Image.LANCZOS)
    big = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    big.paste(src, ((S - src.size[0]) // 2, (S - src.size[1]) // 2))
    with open(marker, "w") as f:
        f.write("%s %s\n" % (hashlib.sha256(open(override, "rb").read()).hexdigest(), os.path.relpath(override, root).replace(os.sep, "/")))
else:
    big = draw()
    if os.path.exists(marker): os.remove(marker)
def png_bytes(size):
    b = io.BytesIO()
    big.resize((size, size), Image.LANCZOS).save(b, "PNG", optimize=True)
    return b.getvalue()

sizes = [16, 24, 32, 48, 64, 128, 256]
pngs = {s: png_bytes(s) for s in sizes}
ico = struct.pack("<HHH", 0, 1, len(sizes))
off = 6 + 16 * len(sizes)
for s in sizes:
    ico += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(pngs[s]), off)
    off += len(pngs[s])
ico += b"".join(pngs[s] for s in sizes)
os.makedirs(os.path.join(root, "assets"), exist_ok=True)
open(os.path.join(root, "assets/quark.ico"), "wb").write(ico)
open(os.path.join(root, "assets/quark.png"), "wb").write(pngs[256])
open(os.path.join(root, "site/icon.png"), "wb").write(pngs[256])
data = pngs[256]
with open(os.path.join(root, "src/launcher/icon_data.h"), "w") as f:
    f.write("// Generated by tools/make_icon.py - the 256x256 quark icon as PNG.\n#pragma once\n")
    f.write("static const unsigned char kIconPng[%d] = {\n" % len(data))
    for i in range(0, len(data), 20):
        f.write("    " + ", ".join(str(b) for b in data[i:i + 20]) + ",\n")
    f.write("};\n")
print("icon written:", len(ico), "bytes")
