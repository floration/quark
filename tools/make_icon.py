#!/usr/bin/env python3
"""Draws the quark icon (cyan 'Q' ring on a dark square with a black outline) and writes:
assets/quark.ico (Windows, PNG entries 16-256), assets/quark.png (256), src/launcher/icon_data.h (embedded PNG)."""
import math, os, struct, zlib, sys
root = sys.argv[1] if len(sys.argv) > 1 else "."

def draw(n):
    px = []
    c = (n - 1) / 2.0
    for y in range(n):
        row = []
        for x in range(n):
            # supersample 4x4 for smooth edges
            acc = [0.0, 0.0, 0.0, 0.0]
            for sy in range(4):
                for sx in range(4):
                    fx = (x + (sx + 0.5) / 4) / n * 2 - 1
                    fy = (y + (sy + 0.5) / 4) / n * 2 - 1
                    col = (0, 0, 0, 0)
                    # rounded square background
                    r = 0.22
                    qx, qy = max(abs(fx) - (1 - r), 0), max(abs(fy) - (1 - r), 0)
                    d = math.hypot(qx, qy)
                    if d < r:
                        col = (0, 0, 0, 255) if d > r - 0.06 else (20, 24, 32, 255)
                        rr = math.hypot(fx, fy)
                        ring = abs(rr - 0.48) < 0.13
                        tail = abs((fx - fy) / math.sqrt(2)) < 0.11 and 0.2 < (fx + fy) / math.sqrt(2) < 0.95
                        if ring or tail:
                            col = (64, 217, 255, 255)
                        elif abs(rr - 0.48) < 0.17 or (abs((fx - fy) / math.sqrt(2)) < 0.15 and 0.15 < (fx + fy) / math.sqrt(2) < 1.0):
                            col = (0, 0, 0, 255)  # outline around the Q
                    for i in range(4): acc[i] += col[i]
            row.append(tuple(int(v / 16) for v in acc))
        px.append(row)
    return px

def png(px):
    n = len(px)
    raw = b"".join(b"\0" + bytes(v for p in row for v in p) for row in px)
    def chunk(t, d): return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", n, n, 8, 6, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")

sizes = [16, 24, 32, 48, 64, 256]
pngs = {s: png(draw(s)) for s in sizes}
ico = struct.pack("<HHH", 0, 1, len(sizes))
off = 6 + 16 * len(sizes)
for s in sizes:
    ico += struct.pack("<BBBBHHII", s % 256, s % 256, 0, 0, 1, 32, len(pngs[s]), off)
    off += len(pngs[s])
ico += b"".join(pngs[s] for s in sizes)
os.makedirs(os.path.join(root, "assets"), exist_ok=True)
open(os.path.join(root, "assets/quark.ico"), "wb").write(ico)
open(os.path.join(root, "assets/quark.png"), "wb").write(pngs[256])
data = pngs[256]
with open(os.path.join(root, "src/launcher/icon_data.h"), "w") as f:
    f.write("// Generated by tools/make_icon.py - the 256x256 quark icon as PNG.\n#pragma once\n")
    f.write("static const unsigned char kIconPng[%d] = {\n" % len(data))
    for i in range(0, len(data), 20):
        f.write("    " + ", ".join(str(b) for b in data[i:i+20]) + ",\n")
    f.write("};\n")
print("icon:", len(ico), "bytes")
