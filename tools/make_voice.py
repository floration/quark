#!/usr/bin/env python3
"""Generates src/client/voice_data.h: the announcer's lines, spoken by espeak-ng, given a little room and
stored as 8-bit samples at 16 kHz in the binary (no sound files to ship). Edit LINES and re-run:
    python3 tools/make_voice.py      (needs espeak-ng)"""
import os, subprocess, tempfile, wave, struct, math

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "client", "voice_data.h")
RATE = 16000
# (id, text): ids match VoiceLine in audio.h
LINES = [
    ("THREE", "three"), ("TWO", "two"), ("ONE", "one"), ("GO", "fight!"),
    ("BOMB_PLANTED", "bomb planted"), ("BOMB_DEFUSED", "bomb defused"),
    ("HILL_TAKEN", "hill captured"), ("HILL_LOST", "hill lost"),
    ("POINT_TAKEN", "point captured"), ("POINT_LOST", "point lost"),
    ("ROUND_WON", "round won"), ("ROUND_LOST", "round lost"), ("OVERTIME", "overtime"),
]

def speak(text):
    with tempfile.TemporaryDirectory() as d:
        p = os.path.join(d, "v.wav")
        subprocess.run(["espeak-ng", "-v", "en-us+m3", "-s", "150", "-p", "28", "-a", "180", "-w", p, text], check=True)
        w = wave.open(p)
        rate, n = w.getframerate(), w.getnframes()
        raw = struct.unpack("<%dh" % n, w.readframes(n))
    x = [v / 32768.0 for v in raw]
    # resample to RATE (linear), trim silence, a short room, normalise to -1 dB
    out, step = [], rate / RATE
    t = 0.0
    while t < len(x) - 1:
        i = int(t); f = t - i
        out.append(x[i] * (1 - f) + x[i + 1] * f)
        t += step
    a = next((i for i, v in enumerate(out) if abs(v) > 0.01), 0)
    b = len(out) - next((i for i, v in enumerate(reversed(out)) if abs(v) > 0.01), 0)
    out = out[max(0, a - 160):min(len(out), b + 400)]
    for delay, gain in ((int(RATE * 0.031), 0.22), (int(RATE * 0.053), 0.14)):
        out = out + [0.0] * delay
        out = [v + (out[i - delay] * gain if i >= delay else 0) for i, v in enumerate(out)]
    peak = max(1e-6, max(abs(v) for v in out))
    return [max(0, min(255, int(round(v / peak * 0.89 * 127 + 128)))) for v in out]

def main():
    parts = ["// generated by tools/make_voice.py (espeak-ng): the announcer's lines, 8-bit unsigned at %d Hz" % RATE,
             "#pragma once", "#include <cstdint>", "#include <cstddef>", "constexpr int kVoiceRate = %d;" % RATE]
    names = []
    for (ident, text) in LINES:
        s = speak(text)
        names.append(ident)
        body = ",".join(str(v) for v in s)
        parts.append("static const uint8_t kVoice_%s[%d] = {%s}; // \"%s\"" % (ident, len(s), body, text))
    parts.append("struct VoiceClip { const uint8_t* data; size_t size; };")
    parts.append("static const VoiceClip kVoiceClips[] = {" + ", ".join("{kVoice_%s, sizeof kVoice_%s}" % (n, n) for n in names) + "};")
    open(OUT, "w").write("\n".join(parts) + "\n")
    print("voice lines written:", ", ".join(names))

main()
