m.box(14, 0, -30, 22, 0.1, -22, accent=True); m.raw("site 14 0 -30 22 3 -22")
for (x, z) in ((-20, -24), (-16, -28), (16, -24), (20, -28)): m.box(x - 1, 0, z - 1, x + 1, 1.4, z + 1)
m.box(-24, 0, -20, -18, 2, -18); m.box(18, 0, -20, 24, 2, -18)          # site walls
