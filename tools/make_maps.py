#!/usr/bin/env python3
"""Generates the per-mode maps in maps/ (symmetric layouts are mirrored so both teams get the same map).
Edit and re-run: python3 tools/make_maps.py"""
import os
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "maps")

class M:
    def __init__(s, title, mode, sun=(0.45, 1.0, 0.3)):
        s.lines = [f"# generated by tools/make_maps.py", f"title {title}", f"for {mode}", "sun %g %g %g" % sun]
    def box(s, x0, y0, z0, x1, y1, z1, accent=False, mirror=False):
        s.lines.append(f"{'accent' if accent else 'box'} {x0:g} {y0:g} {z0:g} {x1:g} {y1:g} {z1:g}")
        if mirror: s.lines.append(f"{'accent' if accent else 'box'} {-x1:g} {y0:g} {-z1:g} {-x0:g} {y1:g} {-z0:g}")
    def room(s, hx, hz, h=8):
        s.box(-hx - 2, -1, -hz - 2, hx + 2, 0, hz + 2)                  # floor
        s.box(-hx - 2, 0, -hz - 2, -hx, h, hz + 2); s.box(hx, 0, -hz - 2, hx + 2, h, hz + 2)
        s.box(-hx, 0, -hz - 2, hx, h, -hz); s.box(-hx, 0, hz, hx, h, hz + 2)
    def spawn(s, team, x, y, z, yaw, mirror_team=None):
        s.lines.append(f"spawn {team} {x:g} {y:g} {z:g} {yaw:g}")
        if mirror_team: s.lines.append(f"spawn {mirror_team} {-x:g} {y:g} {-z:g} {yaw + 180:g}")
    def raw(s, line): s.lines.append(line)
    def stairs(s, x0, z0, x1, z1, top, axis, rising, mirror=False):
        """steps of 0.5 m up to `top` along axis ('x' or 'z'), rising toward +/-"""
        n = int(round(top / 0.5)); length = (x1 - x0) if axis == "x" else (z1 - z0)
        for i in range(n):
            a = length * i / n; b = length * (i + 1) / n
            h = 0.5 * (i + 1) if rising > 0 else 0.5 * (n - i)
            if axis == "x": s.box(x0 + a, 0, z0, x0 + b, h, z1, mirror=mirror)
            else: s.box(x0, 0, z0 + a, x1, h, z0 + b, mirror=mirror)
    def save(s, name):
        open(os.path.join(OUT, name + ".qmap"), "w").write("\n".join(s.lines) + "\n")

# --- duel: small symmetric VS arena, lots of cover, two raised flanks ---------------------------
m = M("Duel", "vs")
m.room(20, 14, 7)
m.box(-1.5, 0, -1.5, 1.5, 3, 1.5, accent=True)                          # center pillar
m.box(-9, 0, -4, -7, 1.6, 4, mirror=True)                               # side walls (crouch-jump cover)
m.box(4, 0, -1, 7, 1.2, 1, mirror=True)                                 # low crates
m.box(-14, 0, 5, -10, 2, 9, mirror=True)                                # raised blocks near spawns
m.stairs(-10, 5, -8, 9, 2, "x", -1, mirror=True)                        # steps onto them
m.box(-3, 0, 8, 3, 1.2, 9, mirror=True)                                 # spawn cover
for x in (-6, 0, 6): m.spawn("a", x, 0, 11.5, 0, "b")
m.spawn("any", -16, 0, 0, 90, "any")
m.save("duel")

