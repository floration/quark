#!/usr/bin/env python3
"""Generates the shipped maps (symmetric layouts are mirrored so both teams get the same map).
The maps are a build artifact: CMake runs this (python3, nothing else needed) and writes them to maps/, which
.gitignore leaves out. Edit the generator and rebuild; never hand-edit the .qmap files it writes.
  tools/maps/prefabs.py     the M builder and the prefabs / helpers more than one map uses
  tools/maps/<name>.py      one module per map: build() makes it and saves it as <name>.qmap
  python3 tools/make_maps.py [--out DIR]   writes every map (default: maps/ next to tools/)
  python3 tools/make_maps.py --map NAME    writes only that map (repeatable)
  python3 tools/make_maps.py --list        prints the names of the maps it makes, writes nothing
  python3 tools/make_maps.py --tidy-report FILE   also writes each map's tidy pass counts (tools/maps/tidy.py)
  python3 tools/make_maps.py --list-legacy prints the legacy maps' names (written to <out>/legacy/)
Each generated map (not the legacy ones) goes through the tidy pass (tools/maps/tidy.py: the map editor's fixers) as it
is saved, in worker processes while the next map is built.
Output is byte-for-byte deterministic (seeded generators only; LF line endings on every platform).
The owner's map overrides win (docs/ASSETS.md): a map with a file at assets/overrides/maps/<name>.qmap is written as
that file (line endings normalised), never generated over it."""
import os, sys, argparse, importlib
sys.dont_write_bytecode = True   # (no __pycache__ in the source tree from a build step)
TOOLS = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, TOOLS)
# every map, in the order they're made (each is tools/maps/<name>.py, saved as <name>.qmap)
MAPS = ["railyard", "dojo", "castle", "qk1", "qk2", "qk3", "qk4", "datacenter", "mine", "qk5", "qk8", "qk6", "qk7",
        "sewer", "war", "rooftoprun", "solar", "jungle", "monorail", "dam", "express",
        "bridge", "convoy", "greenhouse", "orbit", "cruiseship", "fairground", "rooftops",
        "lighthouse", "terraces", "glacier", "spire", "blackhole", "stadium", "tutorial"]
# the old map pool (official until 1.19.6): still built, into <out>/legacy/ (shipped there, never official or ranked;
# the game lists them only with LEGACY MAPS on). Keep in step with kLegacyMapNames (src/game/map.h).
LEGACY = ["clockwork", "depot", "summit", "canal", "harbor", "bastion", "foundry", "temple", "colosseum", "furnace",
          "gantry", "anvil", "viaduct", "hamlet", "downtown", "orbital", "lodestone", "midtown", "hightown", "cascade"]


def result(job, args):
    """a save job's tidy report; a worker that died (no processes to be had here): done again in this process"""
    from concurrent.futures.process import BrokenProcessPool
    from maps import prefabs
    try: return job.result()
    except BrokenProcessPool: return prefabs.finish(*args)


def main():
    ap = argparse.ArgumentParser(description="generate the shipped maps")
    ap.add_argument("--out", default=os.path.join(TOOLS, "..", "maps"))
    ap.add_argument("--map", action="append", choices=MAPS + LEGACY, help="make only this map (repeatable)")
    ap.add_argument("--list", action="store_true", help="print the map names instead of writing the maps")
    ap.add_argument("--tidy-report", metavar="FILE", help="write each map's tidy pass counts (JSON lines) to FILE")
    ap.add_argument("--list-legacy", action="store_true", help="print the legacy map names instead of writing the maps")
    args = ap.parse_args()
    if args.list or args.list_legacy:
        print("\n".join(MAPS if args.list else LEGACY))
        return
    from maps import prefabs
    legacy_out = os.path.join(args.out, "legacy")
    for name in LEGACY:   # (a copy an older build wrote beside the current maps: it would be listed as an unofficial map)
        old = os.path.join(args.out, name + ".qmap")
        if os.path.exists(old):
            with open(old, "rb") as f: generated = f.readline().rstrip(b"\r\n") == b"# generated by tools/make_maps.py"
            if generated: os.remove(old)
    # each map's tidy pass and write (prefabs.finish) go to worker processes while the next map is built: the same
    # output, in less time (in this process when there are no workers to be had)
    try:
        import concurrent.futures
        prefabs.WORKERS = concurrent.futures.ProcessPoolExecutor(max(1, min(4, (os.cpu_count() or 1) - 1))) if (os.cpu_count() or 1) > 1 else None
    except (ImportError, OSError, NotImplementedError):
        prefabs.WORKERS = None
    try:
        for name in args.map or MAPS + LEGACY:
            prefabs.OUT = legacy_out if name in LEGACY else args.out
            prefabs.TIDY = name not in LEGACY   # (the legacy maps ship as they were)
            importlib.import_module("maps." + name).build()
            assert prefabs.MADE and prefabs.MADE[-1] == name, "tools/maps/%s.py must save the map as %r" % (name, name)
        reports = [r for r in (result(j, job) for (j, job) in prefabs.PENDING) if r]
    finally:
        if prefabs.WORKERS: prefabs.WORKERS.shutdown()
    if args.tidy_report:
        import json
        with open(args.tidy_report, "w", newline="\n") as f:
            for r in reports: f.write(json.dumps(r) + "\n")
    print("%d maps written to %s" % (len(prefabs.MADE), os.path.normpath(args.out)))


if __name__ == "__main__":
    main()
