#!/usr/bin/env python3
"""Embed tools/bots/default.qbrain in the game: writes <out>/default_brain.h (kDefaultBrainText, a byte array)."""
import os
import sys

out_dir, src = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read().replace(b'\r\n', b'\n')
lines = []
for i in range(0, len(data), 24):
    lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 24]) + ',')
text = ('// Generated by tools/bots/embed_brain.py from tools/bots/default.qbrain: do not edit.\n'
        '#pragma once\n'
        'static const char kDefaultBrainText[] = {\n' + '\n'.join(lines) + '\n    0x00\n};\n')
os.makedirs(out_dir, exist_ok=True)
path = os.path.join(out_dir, 'default_brain.h')
if not os.path.exists(path) or open(path).read() != text:   # (unchanged: keep the timestamp, no rebuild)
    with open(path, 'w') as f:
        f.write(text)
