#!/usr/bin/env python3
"""Writes tools/weapon_editor/web/js/catalog_data.js, the page's built-in weapon catalog (the MOCK's, and the page's
whenever neither quark_maptool wpnparams nor quark_tests exportweapons answers), from the game itself:
`quark_tests exportweapons` (DESIGN.md section 3). Nothing in it is typed by hand, so it can't drift from
src/game/gamedefs.h / weaponset.cpp: rebuild it after a weapon change.

    python3 tools/weapon_editor/build_catalog.py [--quark-tests PATH] [--check]

--check writes nothing and exits 1 when the file differs from what the game exports now (web/test/run.mjs and
native/test_wpn.py run the same comparison)."""
import json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(HERE, "web", "js", "catalog_data.js")
EXE = ".exe" if os.name == "nt" else ""


def find_quark_tests(given):
    if given: return given
    for d in ("build", "build-release", "build/Release", "build-win"):
        p = os.path.join(REPO, d, "quark_tests" + EXE)
        if os.path.isfile(p): return p
    return None


def export(qt):
    fd, out = tempfile.mkstemp(prefix="qwe-cat-", suffix=".json")
    os.close(fd)
    try:
        r = subprocess.run([qt, "exportweapons", out], capture_output=True, text=True, timeout=120)
        if r.returncode != 0 or os.path.getsize(out) == 0:
            sys.exit("quark_tests exportweapons failed: " + (r.stderr or r.stdout)[-500:])
        with open(out, encoding="utf-8") as f: return json.load(f)
    finally:
        os.remove(out)


def game_version():
    try:
        with open(os.path.join(REPO, "VERSION"), encoding="utf-8") as f: return f.read().strip()
    except OSError:
        return "?"


def render(cat, version):
    """The module text: one field / weapon / slot / builtin per line, so a game change is a readable diff."""
    dump = lambda x: json.dumps(x, ensure_ascii=False, separators=(", ", ": "))
    lines = ["// Generated by tools/weapon_editor/build_catalog.py from `quark_tests exportweapons` (the game's own weapon",
             "// catalog). Don't edit it: rebuild it after a weapon change in src/game (web/test/run.mjs and",
             "// native/test_wpn.py fail while it differs from the game's).",
             "export const GAME_VERSION = %s;" % dump(version),
             "export default {"]
    keys = list(cat.keys())
    for i, k in enumerate(keys):
        v, comma = cat[k], "," if i < len(keys) - 1 else ""
        if isinstance(v, list) and v and isinstance(v[0], dict):
            lines.append("  %s: [" % dump(k))
            lines += ["    %s%s" % (dump(x), "," if j < len(v) - 1 else "") for j, x in enumerate(v)]
            lines.append("  ]" + comma)
        else:
            lines.append("  %s: %s%s" % (dump(k), dump(v), comma))
    lines.append("};")
    return "\n".join(lines) + "\n"


def main():
    args = sys.argv[1:]
    qt = find_quark_tests(args[args.index("--quark-tests") + 1] if "--quark-tests" in args else None)
    if not qt: sys.exit("quark_tests not found: build it (cmake --build build --target quark_tests) or pass --quark-tests")
    text = render(export(qt), game_version())
    old = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
    # (the version line alone doesn't make the catalog stale: a release bump changes nothing in it)
    same = [l for l in old.splitlines() if not l.startswith("export const GAME_VERSION")] == \
           [l for l in text.splitlines() if not l.startswith("export const GAME_VERSION")]
    if "--check" in args:
        print("catalog_data.js matches the game's catalog" if same else
              "catalog_data.js is stale: run python3 tools/weapon_editor/build_catalog.py")
        sys.exit(0 if same else 1)
    if not same:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f: f.write(text)
    print(("wrote " if not same else "up to date: ") + os.path.relpath(OUT, REPO))


if __name__ == "__main__":
    main()
