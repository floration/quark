"""Shared map-building code for tools/make_maps.py: the M builder (boxes, rooms, stairs, ladders, spawns, decor
passes, keep-clear checks, save) and the prefabs and helpers more than one map uses. Each map is its own module
next to this one (tools/maps/<name>.py, a build() that makes and saves it)."""
import os, random, math, contextlib
from collections import Counter
OUT = None   # where save() writes (make_maps.py sets it)
OVERRIDES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "assets", "overrides", "maps")
MADE = []
MAP_FORMAT = 5   # the "version" line every map starts with (src/game/map.h kMapFormatVersion)

class M:
    def __init__(s, title, mode, sun=(0.45, 1.0, 0.3)):
        # (the first line marks a generated map: quark_tests fails it on any map check. A map without it, or with a
        # "handmade" line, is human-made: checked and reported, never failed. See Map::humanMade.)
        s.lines = [f"# generated by tools/make_maps.py", f"version {MAP_FORMAT}", f"title {title}", f"for {mode}" if mode else "# every mode, none in particular", "sun %g %g %g" % sun]
        s.points = {}   # dais(): each capture point's line, by letter (the map writes them in attack order)
    def box(s, x0, y0, z0, x1, y1, z1, accent=False, mirror=False, mat=None):
        kw = mat or ('accent' if accent else 'box')   # mat: box / accent / metal / glow
        s.lines.append(f"{kw} {x0:g} {y0:g} {z0:g} {x1:g} {y1:g} {z1:g}")
        if mirror: s.lines.append(f"{kw} {-x1:g} {y0:g} {-z1:g} {-x0:g} {y1:g} {-z0:g}")
    def metal(s, *a, **k): s.box(*a, mat="metal", **k)
    def glow(s, *a, **k): s.box(*a, mat="glow", **k)
    # ---- rooms: floors with holes (pits / water / molten channels) and sunken areas ----
    def room(s, hx, hz, h=8, pits=(), sunken=(), style="hall", skyline=None, wall_base=None, walls=True, tile=None):
        """the arena: floor, four walls. pits = [(x0, z0, x1, z1, kind)] are holes you fall through and die
        (kind: molten / water / abyss / chasm); sunken = [(x0, z0, x1, z1, depth, mat)] are lower floors.
        style picks the wall dress (hall / temple / yard / fort), skyline the distant scenery."""
        s.hx, s.hz, s.h, s.style, s.skyline, s.walls = hx, hz, h, style, skyline, walls
        s.pits = [tuple(p) for p in pits]
        s.sunken = [tuple(p) for p in sunken]
        s.holes = [p[:4] for p in s.pits] + [p[:4] for p in s.sunken]
        deep = any(p[4] == "chasm" for p in s.pits)
        s.wall_base = wall_base if wall_base is not None else (-12 if deep else -4 if s.pits else 0)
        if s.pits: s.raw("void -2.5")
        for (x0, z0, x1, z1) in tiles(minus((-hx - 2, -hz - 2, hx + 2, hz + 2), s.holes), tile):
            s.box(x0, -1, z0, x1, 0, z1)                                         # floor around the holes
        wb = s.wall_base
        if walls:   # (castle / factory maps build their own shell)
            s.box(-hx - 2, wb, -hz - 2, -hx, h, hz + 2); s.box(hx, wb, -hz - 2, hx + 2, h, hz + 2)
            s.box(-hx, wb, -hz - 2, hx, h, -hz); s.box(-hx, wb, hz, hx, h, hz + 2)
            s.clip_walls(-hx, -hz, hx, hz, h)
        if deep:   # the chasm keeps going: unlit rock far below
            s.box(-hx - 2, -60, -hz - 2, -hx, wb, hz + 2, mat="far"); s.box(hx, -60, -hz - 2, hx + 2, wb, hz + 2, mat="far")
            s.box(-hx, -60, -hz - 2, hx, wb, -hz, mat="far"); s.box(-hx, -60, hz, hx, wb, hz + 2, mat="far")
            s.box(-hx, -61, -hz, hx, -60, hz, mat="far")
        for (x0, z0, x1, z1, kind) in s.pits:
            if kind == "chasm": continue
            bot = -3.6 if kind in ("molten", "water") else -14
            if kind in ("molten", "water"):   # a visible surface just below the floor (not solid: in you go, and die).
                s.box(x0, -1.4, z0, x1, -1.2, z1, mat="lava" if kind == "molten" else "water")   # no shaft lining: the
                continue                                                                          # surface hides the shaft
            for (a, b, c, d) in ((x0 - 0.5, z0 - 0.5, x1 + 0.5, z0), (x0 - 0.5, z1, x1 + 0.5, z1 + 0.5), (x0 - 0.5, z0, x0, z1), (x1, z0, x1 + 0.5, z1)):
                s.box(a, bot, b, c, -1, d, accent=True)                          # shaft lining under the floor edge
            s.box(x0, bot - 0.5, z0, x1, bot + 0.6, z1, mat="metal")
            if kind == "molten": s.light((x0 + x1) / 2, -1.0, (z0 + z1) / 2, max(x1 - x0, z1 - z0) * 0.7 + 3, 0.9, fixture=False)
        for (x0, z0, x1, z1, depth, mat) in s.sunken:
            s.box(x0, -depth - 1, z0, x1, -depth, z1, mat=mat)
            for (a, b, c, d) in ((x0 - 0.5, z0 - 0.5, x1 + 0.5, z0), (x0 - 0.5, z1, x1 + 0.5, z1 + 0.5), (x0 - 0.5, z0, x0, z1), (x1, z0, x1 + 0.5, z1)):
                s.box(a, -depth - 1, b, c, -1, d, accent=True)
    def clip_walls(s, x0, z0, x1, z1, h, up=80):
        """invisible clip on top of the outer walls, up out of reach: nobody hooks or jumps out of the map
        (players only: shots, hooks and sight go through)"""
        s.box(x0 - 2, h, z0 - 2, x0, h + up, z1 + 2, mat="clip"); s.box(x1, h, z0 - 2, x1 + 2, h + up, z1 + 2, mat="clip")
        s.box(x0, h, z0 - 2, x1, h + up, z0, mat="clip"); s.box(x0, h, z1, x1, h + up, z1 + 2, mat="clip")
    # ---- the keep-clear registry (REVIEW MAP-5): volumes nothing solid may stand in (the payload cart's sweep along
    # its track, a lane's narrow openings, ...). save() checks every placement against it: generated decor (dress,
    # props, detail, skyline, clutter, cribs, scatter) that lands in one is dropped; anything placed by hand there
    # stops the build with the line and the volume it's in.
    def keep_clear_box(s, x0, y0, z0, x1, y1, z1, why, mirror=False):
        s.__dict__.setdefault("clear_boxes", []).append((min(x0, x1), min(y0, y1), min(z0, z1), max(x0, x1), max(y0, y1), max(z0, z1), why))
        if mirror: s.keep_clear_box(-x1, y0, -z1, -x0, y1, -z0, why)
    @contextlib.contextmanager
    def generated(s):
        """the lines added inside are generated decor (dropped, not an error, where they'd block a keep-clear volume)"""
        before = Counter(s.lines)
        yield
        s.__dict__.setdefault("auto_lines", Counter()).update(Counter(s.lines) - before)
    def cart_clear(s):
        """the payload cart's sweep (its box: 2.4 x 1.8 x 1.5 m, Map::payloadCartBox) along every leg of the track,
        with 10 cm to spare, into the registry"""
        path = [tuple(map(float, l.split()[1:4])) for l in s.lines if l.startswith("path ")]
        for (ax, ay, az), (bx, by, bz) in zip(path, path[1:]):
            lo, hi = min(ay, by) + 0.02, max(ay, by) + 1.6
            if abs(bx - ax) >= abs(bz - az): s.keep_clear_box(min(ax, bx) - 1.3, lo, az - 1.0, max(ax, bx) + 1.3, hi, bz + 1.0, "the payload cart's track")
            else: s.keep_clear_box(ax - 1.0, lo, min(az, bz) - 1.3, bx + 1.0, hi, max(az, bz) + 1.3, "the payload cart's track")
    def check_clear(s):
        """every solid (or visible) box against the keep-clear registry: generated ones in a volume go, hand-placed
        ones are an error"""
        boxes = getattr(s, "clear_boxes", [])
        if not boxes: return
        auto = getattr(s, "auto_lines", Counter())
        kinds = {"box", "accent", "wallbang", "metal", "glow", "trim", "clip"}
        out, errors = [], []
        for l in s.lines:
            w = l.split()
            if w and w[0] in kinds and len(w) == 7:
                b = tuple(map(float, w[1:7]))
                hit = next((z for z in boxes if b[0] < z[3] - 1e-3 and b[3] > z[0] + 1e-3 and b[1] < z[4] - 1e-3 and b[4] > z[1] + 1e-3
                            and b[2] < z[5] - 1e-3 and b[5] > z[2] + 1e-3), None)
                if hit:
                    if auto[l] > 0: auto[l] -= 1; continue
                    errors.append(f"  {l}   is in {hit[6]} ({' '.join(f'{v:g}' for v in hit[:6])})")
            out.append(l)
        if errors: raise SystemExit(f"make_maps.py: {s.name}: placed in a keep-clear volume (move it, or the volume):\n" + "\n".join(errors))
        s.lines = out
    def keep_clear(s, x0, z0, x1, z1, y=2.4):
        """a doorway (and the step in front and behind it): nothing placed later may stand in it"""
        s.__dict__.setdefault("clear_zones", []).append((x0, z0, x1, z1, y))
    def clear_doorways(s):
        """drop solid props / dressing that ended up in a doorway (walls beside it only touch the zone's edge)"""
        zones = getattr(s, "clear_zones", [])
        if not zones: return
        solid = {"box", "accent", "metal", "wallbang", "trim", "glow"}
        out = []
        for l in s.lines:
            w = l.split()
            if w and w[0] in solid and len(w) >= 7:
                x0, y0, z0, x1, y1, z1 = map(float, w[1:7])
                if y1 > 0.3 and any(x0 < b[2] - 1e-3 and x1 > b[0] + 1e-3 and z0 < b[3] - 1e-3 and z1 > b[1] + 1e-3 and y0 < b[4] for b in zones): continue
            out.append(l)
        s.lines = out
    def scale_xz(s, f):
        """spread everything built so far out by f across the ground (heights unchanged): a map made roomier
        without moving every piece by hand. Boxes, stairs, ladders, spawns and lights; lights reach f as far."""
        boxes = {"box", "accent", "wallbang", "metal", "glow", "far", "water", "lava", "trim", "clip", "nograpple", "acid", "ladder"}
        g = lambda v: f"{float(v) * f:g}"
        def scaled(l):
            w = l.split()
            if w and w[0] in boxes and len(w) >= 7: w[1], w[3], w[4], w[6] = g(w[1]), g(w[3]), g(w[4]), g(w[6])
            elif w and w[0] == "spawn": w[2], w[4] = g(w[2]), g(w[4])
            elif w and w[0] == "light": w[1], w[3], w[4] = g(w[1]), g(w[3]), g(w[4])
            elif w and w[0] == "stairs": w[1], w[2], w[3], w[4] = g(w[1]), g(w[2]), g(w[3]), g(w[4])
            return " ".join(w) if w and (w[0] in boxes or w[0] in ("spawn", "light", "stairs")) else l
        s.lines = [scaled(l) for l in s.lines]
        if hasattr(s, "auto_lines"): s.auto_lines = Counter({scaled(l): n for l, n in s.auto_lines.items()})
        s.clear_boxes = [tuple(v * f if i in (0, 2, 3, 5) else v for i, v in enumerate(z[:6])) + (z[6],) for z in getattr(s, "clear_boxes", [])]
        if hasattr(s, "hx"):
            s.hx, s.hz = s.hx * f, s.hz * f
            sc = lambda r: tuple(v * f for v in r[:4]) + tuple(r[4:])
            s.pits, s.sunken, s.holes = [sc(p) for p in s.pits], [sc(p) for p in s.sunken], [sc(p) for p in s.holes]
    def over_hole(s, x, z, r=0.0):
        return any(x0 - r < x < x1 + r and z0 - r < z < z1 + r for (x0, z0, x1, z1) in getattr(s, "holes", []))
    def stairs(s, x0, z0, x1, z1, top, axis, rising, mirror=False, base=0.0, solid=True):
        """steps of 0.5 m from `base` up to `top` along axis ('x' or 'z'), rising toward +/-; solid=False makes
        each step a 1 m slab (a flight in the air, nothing underneath) instead of a block down to the ground"""
        # recorded for quark_tests' stairs check (group maps: every flight is walked, and checked against the paths around it)
        s.lines.append(f"stairs {x0:g} {z0:g} {x1:g} {z1:g} {base:g} {top:g} {axis} {rising:g} {int(solid)}")
        if mirror: s.lines.append(f"stairs {-x1:g} {-z1:g} {-x0:g} {-z0:g} {base:g} {top:g} {axis} {-rising:g} {int(solid)}")
        n = max(1, math.ceil((top - base) / 0.5 - 1e-6)); length = (x1 - x0) if axis == "x" else (z1 - z0)   # (every rise <= 0.5 m: the step-up is 0.55)
        for i in range(n):
            a = length * i / n; b = length * (i + 1) / n
            h = base + (top - base) * ((i + 1) if rising > 0 else (n - i)) / n
            y0 = min(base, 0) - (1 if base < 0 else 0) if solid else h - 1
            if axis == "x": s.box(x0 + a, y0, z0, x0 + b, h, z1, mirror=mirror)
            else: s.box(x0, y0, z0 + a, x1, h, z0 + b, mirror=mirror)
    def building(s, x0, z0, x1, z1, h, doors, roof=True, windows=False, lights=True, mirror=False, base=0.0, notch=None):
        """a walled building with doorways and a roof: doors = [(side, center, width)], side in n/s/w/e"""
        t = 0.4
        sides = {"n": (x0, z0, x1, z0 + t, "x"), "s": (x0, z1 - t, x1, z1, "x"), "w": (x0, z0, x0 + t, z1, "z"), "e": (x1 - t, z0, x1, z1, "z")}
        for k, (a, b, c, d, ax) in sides.items():
            ds = [(cc, w, min(2.6, h - 0.4)) for (sd, cc, w) in doors if sd == k]
            if windows and k in ("n", "s"):
                s.windowwall(a, b, c, d, h, 1.1, min(2.3, h - 0.6), every=3.0, width=1.4, mirror=mirror, base=base) if not ds else s.doorwall(a, b, c, d, h, ds, axis=ax, mirror=mirror, base=base)
            else:
                s.doorwall(a, b, c, d, h, ds, axis=ax, mirror=mirror, base=base)
        if roof:
            y = base + h
            notches = (notch if isinstance(notch, list) else [notch]) if notch else []
            for (a, b, c, d) in minus((x0 - 0.3, z0 - 0.3, x1 + 0.3, z1 + 0.3), notches):   # notch(es): open above a ladder / stairs
                s.box(a, y, b, c, y + 0.35, d, accent=True, mirror=mirror)
            for strip in ((x0 - 0.32, z0 - 0.32, x1 + 0.32, z0 - 0.3), (x0 - 0.32, z1 + 0.3, x1 + 0.32, z1 + 0.32)):
                for (a, b, c, d) in minus(strip, notches): s.glow(a, y - 0.1, b, c, y, d, mirror=mirror)
            if lights: s.light((x0 + x1) / 2, y - 0.6, (z0 + z1) / 2, max(x1 - x0, z1 - z0) * 0.8 + 2, 0.8, mirror=mirror)
    def spawn(s, team, x, y, z, yaw, mirror_team=None):
        s.lines.append(f"spawn {team} {x:g} {y:g} {z:g} {yaw:g}")
        if mirror_team: s.lines.append(f"spawn {mirror_team} {-x:g} {y:g} {-z:g} {yaw + 180:g}")
    def raw(s, line): s.lines.append(line)
    # ---- spawn pools (REVIEW MAP-2): every mode a map offers has a spawn for each player a full default-size server
    # (8) puts in its pool: free for all, hide, tag and a tourney's warm-up draw from the "any" spawns, race from the
    # race spawns. save() tops short pools up from open floor (quark_tests maps checks every pool spawnPlayer uses).
    POOL = 8
    def spawn_spots(s, ys, band=0.6):
        """open standing spots on the floors at heights ys: solid floor under the whole hull, nothing within 0.6 m of
        it up to 2.4 m (pads stay clean), clear of objectives, stairs, ladders, the cart's track, keep-clear volumes
        and other spawns, on this side of any clip (an invisible wall) from the nearest spawn already there, and only
        where players can walk to from the spawns on that floor"""
        kinds = {"box", "accent", "wallbang", "metal", "glow", "clip"}
        solid, avoid, spawns, path, clips = [], [], [], [], []
        for l in s.lines:
            w = l.split()
            if not w: continue
            if w[0] in kinds and len(w) == 7:
                solid.append(tuple(map(float, w[1:7])))
                if w[0] == "clip": clips.append(solid[-1])
            elif w[0] in ("water", "lava", "ladder") and len(w) >= 7: avoid.append(tuple(map(float, w[1:7])))
            elif w[0] in ("site", "hill", "point", "checkpoint") and len(w) >= 7:
                b = tuple(map(float, w[1:7])); avoid.append((b[0] - 2, b[1] - 1, b[2] - 2, b[3] + 2, b[4] + 1, b[5] + 2))
            elif w[0] == "spawn": spawns.append(tuple(map(float, w[2:5])))
            elif w[0] == "path": path.append((float(w[1]), float(w[3])))
            elif w[0] == "stairs":
                a = list(map(float, w[1:5])); avoid.append((a[0] - 1.5, -1e9, a[1] - 1.5, a[2] + 1.5, 1e9, a[3] + 1.5))
        avoid += [z[:6] for z in getattr(s, "clear_boxes", [])]
        cell = 4.0
        grid = {}
        for i, b in enumerate(solid):
            for gx in range(int(math.floor(b[0] / cell)), int(math.floor(b[3] / cell)) + 1):
                for gz in range(int(math.floor(b[2] / cell)), int(math.floor(b[5] / cell)) + 1): grid.setdefault((gx, gz), []).append(i)
        def near(x0, z0, x1, z1):
            seen = set()
            for gx in range(int(math.floor(x0 / cell)), int(math.floor(x1 / cell)) + 1):
                for gz in range(int(math.floor(z0 / cell)), int(math.floor(z1 / cell)) + 1):
                    for i in grid.get((gx, gz), ()):
                        if i not in seen: seen.add(i); yield solid[i]
        def hits(q):
            return any(b[0] < q[3] and b[3] > q[0] and b[1] < q[4] and b[4] > q[1] and b[2] < q[5] and b[5] > q[2] for b in near(q[0], q[2], q[3], q[5]))
        def inside(x, y, z):
            return any(b[0] < x < b[3] and b[1] < y < b[4] and b[2] < z < b[5] for b in near(x, z, x, z))
        def floor_at(x, z, y):   # (a spawn may stand a little above its floor: Dojo's are 0.1 m up, on the mat)
            return any(y - 0.15 <= b[4] <= y + 0.01 and b[0] <= x <= b[3] and b[2] <= z <= b[5] for b in near(x, z, x, z))
        def through_clip(x, y, z):   # the line from here to the nearest spawn crosses an invisible wall
            if not spawns: return False
            p = min(spawns, key=lambda q: math.hypot(q[0] - x, q[2] - z))
            for k in range(1, 41):
                t = k / 40; qx, qz = x + (p[0] - x) * t, z + (p[2] - z) * t
                if any(b[0] < qx < b[3] and b[2] < qz < b[5] and b[1] < y + 1 < b[4] for b in clips): return True
            return False
        s._inside = inside
        def seg_d(px, pz, a, b):
            dx, dz = b[0] - a[0], b[1] - a[1]; L = dx * dx + dz * dz
            t = 0 if L == 0 else max(0, min(1, ((px - a[0]) * dx + (pz - a[1]) * dz) / L))
            return math.hypot(px - a[0] - t * dx, pz - a[1] - t * dz)
        xs = [b[0] for b in solid] + [b[3] for b in solid]; zs = [b[2] for b in solid] + [b[5] for b in solid]
        hx, hz = (s.hx, s.hz) if hasattr(s, "hx") else (max(map(abs, xs)), max(map(abs, zs)))
        step = 1.0 if hx * hz < 1500 else 2.0
        def cell_h(x, z, y):   # the floor a hull stands on here, within `band` of height y (None: no room / no floor)
            for t in sorted({b[4] for b in near(x, z, x, z) if b[0] <= x <= b[3] and b[2] <= z <= b[5] and y - band <= b[4] <= y + band}, reverse=True):
                if not hits((x - 0.4, t + 0.01, z - 0.4, x + 0.4, t + 1.8, z + 0.4)): return t
            return None
        out = []
        x0g, z0g = -math.floor(hx) + 1.0, -math.floor(hz) + 1.0
        nxg, nzg = int((hx - 1 - x0g) / step) + 1, int((hz - 1 - z0g) / step) + 1
        for y in ys:
            # flood the floor at about this height from the spawns already on it (walking: steps of 0.55 m, the hull
            # swept between grid points): only spots players can walk to from them (no sealed rooms, no rooftops)
            h, todo = {}, []
            for p in spawns:
                if abs(p[1] - y) > band: continue
                i, k = round((p[0] - x0g) / step), round((p[2] - z0g) / step)
                for (di, dk) in sorted(((a, c) for a in (-1, 0, 1) for c in (-1, 0, 1)), key=lambda q: abs(q[0]) + abs(q[1])):
                    if (i + di, k + dk) in h: break
                    t = cell_h(x0g + (i + di) * step, z0g + (k + dk) * step, y) if 0 <= i + di < nxg and 0 <= k + dk < nzg else None
                    if t is not None: h[(i + di, k + dk)] = t; todo.append((i + di, k + dk)); break
            while todo:
                i, k = todo.pop()
                for (di, dk) in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    c = (i + di, k + dk)
                    if c in h or not (0 <= c[0] < nxg and 0 <= c[1] < nzg): continue
                    xa, za, xb, zb = x0g + i * step, z0g + k * step, x0g + c[0] * step, z0g + c[1] * step
                    t = cell_h(xb, zb, y)
                    if t is None or abs(t - h[(i, k)]) > 0.55: continue
                    top = max(t, h[(i, k)])
                    if hits((min(xa, xb) - 0.4, top + 0.01, min(za, zb) - 0.4, max(xa, xb) + 0.4, top + 1.8, max(za, zb) + 0.4)): continue
                    h[c] = t; todo.append(c)
            for (i, k) in sorted(h):
                x, z = x0g + i * step, z0g + k * step
                if hasattr(s, "hx") and (abs(x) > s.hx - 2.5 or abs(z) > s.hz - 2.5): continue   # (dress() lines the walls)
