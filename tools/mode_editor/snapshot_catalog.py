#!/usr/bin/env python3
"""Refresh web/js/catalog_snapshot.js from the game: the page's catalog when serve.py has no quark_tests with
exportmode (an installed copy without a build, say). Run it after the mode catalog changes (src/game/modelogic*):

    python3 tools/mode_editor/snapshot_catalog.py [--quark-tests build/quark_tests]

It keeps only the catalog (not the built-in texts: those come from tools/modes/*.qlogic) and writes it sorted, so the
diff shows what changed.
"""
import argparse, json, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "web", "js", "catalog_snapshot.js")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quark-tests", default=os.path.join(HERE, "..", "..", "build", "quark_tests" + (".exe" if os.name == "nt" else "")))
    a = ap.parse_args()
    if not os.path.isfile(a.quark_tests):
        print("quark_tests not found: %s" % a.quark_tests); return 1
    with open(a.quark_tests, "rb") as f:
        if b"exportmode\x00" not in f.read():   # (an unknown command would run the whole test suite)
            print("this quark_tests has no exportmode"); return 1
    with tempfile.TemporaryDirectory() as td:
        out = os.path.join(td, "modes.json")
        subprocess.run([a.quark_tests, "exportmode", out], check=True, capture_output=True, timeout=300)
        with open(out, encoding="utf-8") as f: doc = json.load(f)
    cat = doc.get("catalog", doc)
    commit = ""
    try:
        commit = subprocess.run(["git", "-C", HERE, "rev-parse", "--short", "HEAD"], capture_output=True, text=True, timeout=10).stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        pass
    body = json.dumps(cat, indent=1, sort_keys=True, ensure_ascii=False)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by tools/mode_editor/snapshot_catalog.py from `quark_tests exportmode` (format %s, at %s): the\n"
                "// game's mode catalog, used when serve.py can't run exportmode. Don't edit by hand; run the script again.\n"
                % (doc.get("format", "?"), commit or "?"))
        f.write("export const SNAPSHOT_SOURCE = %s;\n" % json.dumps("quark_tests exportmode at " + (commit or "?")))
        f.write("export const SNAPSHOT = " + body + ";\n")
    print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
