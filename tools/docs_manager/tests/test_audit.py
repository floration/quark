class BlocksTests(unittest.TestCase):
    def test_not_itself(self):
        h = entry("02-currently-working-on.md", "Approve it", priority="HALT", thread="q", threadRaw="q")
        work = entry("02-currently-working-on.md", "Real work", status="in-progress", thread="q")
        self.assertEqual(serve._blocks(h, [h, work]), ("a Claude agent", None))
        h2 = entry("02-currently-working-on.md", "Pick", priority="HALT")
        w2 = entry("02-currently-working-on.md", "Feel review", status="in-progress")
        self.assertEqual(serve._blocks(h2, [h2, w2]), ("Tweak gameplay: Feel review", w2["id"]))
        self.assertEqual(serve._blocks(h2, [h2]), ("Tweak gameplay", None))


class CommitThreadTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.mgr = serve.Manager.__new__(serve.Manager)
        cls.mgr.threads = [{"title": "Build a sound editor for the game", "url": "https://claude.ai/x", "aliases": ["Sound editor"]}]

    def th(self, subject, items=(), et=None):
        linker = serve.ghlinks.Linker({}, self.mgr.threads)
        return self.mgr.commit_thread(subject, linker, items, et or {})[0]

    def test_threads(self):
        et = {"02-currently-working-on.md:claim": "Fix the app audit", "09-answers-from-q.md:q": "q"}
        self.assertEqual(self.th('09/07: q answered "X" (Claude Manager)', [{"entryId": "09-answers-from-q.md:q"}], et), "q")
        self.assertEqual(self.th('03: q added "Y" (Claude Manager)'), "q")
        self.assertEqual(self.th("13: audit (Fix the app audit); 01/03 entries", (), et), "Fix the app audit")
        self.assertEqual(self.th("Sound editor: merged"), "Build a sound editor for the game")
        self.assertEqual(self.th("02: claim the audit fixes", [{"entryId": "02-currently-working-on.md:claim"}], et), "Fix the app audit")
        self.assertIsNone(self.th("02: something", [{"entryId": "gone"}], et))


