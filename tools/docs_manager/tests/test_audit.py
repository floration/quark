def entry(file, title, status="open", body="Body.", section="S", **kw):
    e = {"id": "%s:%s" % (file, docsparse.slug(title)), "file": file, "section": section, "title": title, "priority": None,
         "body": body, "date": "2026-10-23", "thread": "Tweak gameplay", "status": status, "statusNote": "", "statusText": status,
         "archived": False, "line": 1, "links": []}
    e.update(kw)
    return e


class TrailerTailTests(unittest.TestCase):
    def test_text_after_trailer(self):
        t = ("# Working on\n\n## Done\n\n- **UI redesign in the game.** Shipped. _2026-10-24, UI redesign, done_ Follow-up: hyper hop "
             "3x higher.\n- **Log downloads.** Unverified. _2026-10-24, GitHub manager, fixed_ (gh 2.10x needed a flag)\n"
             "- **Plain.** Text with a date _2026-10-20_ inside and no trailer.\n")
        es = {e["title"]: e for e in docsparse.parse_file("02-currently-working-on.md", t)["entries"]}
        u = es["UI redesign in the game."]
        self.assertEqual((u["status"], u["tail"], u["statusNote"]), ("done", "Follow-up: hyper hop 3x higher.", "Follow-up: hyper hop 3x higher."))
        self.assertEqual(u["body"], "Shipped.")
        self.assertEqual((es["Log downloads."]["status"], es["Log downloads."]["tail"]), ("fixed", "(gh 2.10x needed a flag)"))
        p = es["Plain."]                                                    # a body date without ', thread, status' is not a trailer
        self.assertEqual((p["status"], p["hasTrailer"], p["tail"]), ("unknown", False, ""))

    def test_answer_keeps_tail(self):
        import docsedit
        lines = ["- **Q?** Body. _2026-10-23, Tweak gameplay, open_ (see 08)"]
        e = docsparse.parse_file("07-things-to-ask-the-user.md", "\n".join(lines))["entries"][0]
        docsedit.set_answer_trailer(lines, e, "yes", "2026-10-24", ["Tweak gameplay"])
        self.assertEqual(lines[0], "- **Q?** Body. _2026-10-23, Tweak gameplay, answered: yes (q, via Claude Manager)_ (see 08)")


class FileKindTests(unittest.TestCase):
    def test_generated_and_reports(self):
        gen = "# GitHub rules\n\n> Generated by the GitHub Manager; edit there.\n\n## Pushing\n\n- **Only q pushes** (locked)\n"
        self.assertEqual(docsparse.file_kind("10-github-rules.md", gen), "document")
        self.assertTrue(docsparse.parse_file("10-github-rules.md", gen)["generated"])
        report = "# 13: audit\n\n## Tab\n\n" + "".join("- **[low] Item %d** detail\n" % i for i in range(8))
        self.assertEqual(docsparse.file_kind("13-app-audit.md", report), "document")
        self.assertEqual(docsparse.parse_file("13-app-audit.md", report)["entries"], [])
        notes = "# Other\n\n" + "".join("- **N%d.** x%s\n" % (i, " _2026-10-23, T_" if i % 3 else "") for i in range(9))
        self.assertEqual(docsparse.file_kind("08-other.md", notes), "entries")    # 6 of 9 carry the italic
        self.assertEqual(docsparse.file_kind("12-play-notes.md", "# Play notes\n\n## Notes\n\n## Archive\n"), "entries")
        self.assertEqual(docsparse.file_kind("01-known-bugs.md"), "entries")

    # PR #70 put a status trailer on most of 13's bullets, so the 1-in-5 share read the report as 397 entries again.
    TRAILED = ("# 13: audit\n\nScores per tab.\n\n## 1. Tab: 7/10\n\n### Wrong\n\n" +
               "".join("- **[low] Item %d** detail. (`a.js:1`) _2026-10-24 13:15 CT, Fix the audit findings, fixed in PR #70: "
                       "done (abc1234)._\n" % i for i in range(12)) +
               "\n### Missing\n\n" + "".join("- **Feature %d** wanted. _2026-10-24 13:15 CT, Fix the audit findings, added in "
                                               "PR #70: Open, Reload and Copy._\n" % i for i in range(4)) +
               "\n### Not tested\n\n- Windows-only paths: needs q's PC.\n")

    def test_report_with_trailers(self):
        self.assertEqual(docsparse.kind_reason("13-app-audit.md", self.TRAILED), ("document", "report-name"))
        self.assertEqual(docsparse.parse_file("13-app-audit.md", self.TRAILED)["entries"], [])
        self.assertEqual(docsparse.file_kind("13-app-audit.md"), "document")             # (name only: docsedit's checks)
        for name in ("14-security-audit.md", "15-report.md", "16-perf-reports-oct.md"):
            self.assertEqual(docsparse.file_kind(name), "document", name)
        for name in ("12-play-notes.md", "14-auditions.md", "15-reporting-bugs.md"):
            self.assertEqual(docsparse.file_kind(name), "entries", name)
        # any other name: the file says what it is
        self.assertEqual(docsparse.file_kind("14-pass-two.md", self.TRAILED), "entries")
        marked = self.TRAILED.replace("Scores per tab.", "> Kind: report\n\nScores per tab.")
        self.assertEqual(docsparse.kind_reason("14-pass-two.md", marked), ("document", "declared"))
        self.assertEqual(docsparse.lint("14-pass-two.md", marked), [])
        self.assertEqual(docsparse.file_kind("14-pass-two.md", marked.replace("Kind: report", "kind: Document")), "document")
        forced = self.TRAILED.replace("Scores per tab.", "> Kind: entries")
        self.assertEqual(docsparse.kind_reason("13-app-audit.md", forced), ("entries", "declared"))
        self.assertEqual(len(docsparse.parse_file("13-app-audit.md", forced)["entries"]), 17)
        late = self.TRAILED + "\n" * 3 + "x" * 1600 + "\n> Kind: report\n"                  # (only near the top counts)
        self.assertEqual(docsparse.file_kind("14-pass-two.md", late), "entries")

    @unittest.skipUnless(os.environ.get("QUARK_DOCS_REPO"), "set QUARK_DOCS_REPO to a Claude Documents clone")
    def test_real_trailer_heavy_13(self):
        import subprocess
        r = subprocess.run(["git", "-C", os.environ["QUARK_DOCS_REPO"], "show", "1ea948c:13-app-audit.md"], capture_output=True)
        if r.returncode: self.skipTest("this clone has no commit 1ea948c")
        text = r.stdout.decode("utf-8")
        self.assertEqual(docsparse.file_kind("13-app-audit.md", text), "document")
        self.assertEqual(docsparse.parse_file("13-app-audit.md", text)["entries"], [])


class LintTests(unittest.TestCase):
    TEXT = ("# Possible bugs\n\n## Game\n\n"
            "- **Good one.** Body. _2026-10-23, Tweak gameplay, open_\n"            # 5
            "- **Sections below `## From the gamemode thread\n\n"                   # 6: never closed
            "## Archive`.** 01 has stuff after Archive. _2026-10-24, Docs, open_\n\n"  # 8: split-off heading
            "- **No trailer.** Body only.\n"                                        # 10
            "- **Odd.** Body. _2026-10-23, Tweak gameplay, whatever_\n"              # 11
            "- **Good one.** Again. _2026-10-23, Tweak gameplay, open_\n"           # 12
            "- **Tail.** Body. _2026-10-23, Tweak gameplay, done_ More words.\n\n"  # 13
            "## Archive\n\n"
            "- **Still open.** Body. _2026-10-22, Tweak gameplay, open_\n\n"        # 17
            "## Late section\n\n"                                                  # 19
            "- **Below archive.** Body. _2026-10-22, Tweak gameplay, open_\n")

    def test_problems(self):
        probs = docsparse.lint("03-possible-bugs.md", self.TEXT)
        got = {(p["line"], p["code"]) for p in probs}
        for want in [(6, "unclosed-title"), (8, "heading-in-entry"), (10, "no-status"), (11, "bad-status"), (12, "duplicate-title"),
                     (13, "text-after-status"), (17, "open-in-archive"), (19, "after-archive")]:
            self.assertIn(want, got)
        self.assertNotIn(5, {p["line"] for p in probs})
        sev = {p["code"]: p["severity"] for p in probs}
        self.assertEqual((sev["heading-in-entry"], sev["no-status"], sev["open-in-archive"]), ("error", "warn", "info"))
        self.assertEqual(probs, sorted(probs, key=lambda p: p["line"]))
        self.assertTrue(all(p["file"] == "03-possible-bugs.md" for p in probs))

    def test_notes_and_documents(self):
        self.assertEqual(docsparse.lint("08-other.md", "# Other\n\n- **Note.** No status here.\n"), [])
        report = "# 13\n\n" + "".join("- **[low] Item %d** detail\n" % i for i in range(6))
        self.assertEqual([p["code"] for p in docsparse.lint("14-pass-two.md", report)], ["read-as-document"])
        self.assertEqual(docsparse.lint("13-app-audit.md", report), [])                   # (a report by its name: nothing to say)
        gen = "# GitHub notes\n\n> Generated by the GitHub Manager.\n\nNo notes yet.\n"
        self.assertEqual(docsparse.lint("11-github-notes.md", gen), [])
        self.assertEqual(docsparse.lint("00-agent-rules.md", "# Rules\n\n- a rule\n"), [])


class WaitingTests(unittest.TestCase):
    def w(self, e, answer=None):
        return serve.waiting_on(e, [], answer)

    def test_reference_archived_read(self):
        self.assertEqual(self.w(entry("08-other.md", "N", status="open"))[:2], (["none"], "Nothing: a reference note."))
        self.assertEqual(self.w(entry("07-things-to-ask-the-user.md", "Hosting?", archived=True, section="Archive"))[:2],
                         (["none"], "Nothing: archived."))
        self.assertEqual(self.w(entry("06-things-to-tell-the-user.md", "News"))[:2], (["read"], "Not told yet: for q to read."))
        self.assertEqual(self.w(entry("09-answers-from-q.md", "Q?"))[0], ["answered"])

    def test_answered_original(self):
        a = entry("09-answers-from-q.md", "News", date="2026-10-24")
        w, why, _ = self.w(entry("06-things-to-tell-the-user.md", "News"), a)
        self.assertEqual((w, why), (["answered"], "q answered (09, 2026-10-24); waiting on a Claude to act on it."))
        w, why, _ = self.w(entry("02-currently-working-on.md", "X", status="in-progress", body="Waiting on the owner's push."), a)
        self.assertEqual(w, ["answered"])
        self.assertEqual(self.w(entry("01-known-bugs.md", "B"), a)[0], ["claude"])    # didn't wait on q: unchanged
        self.assertEqual(serve.title_key("**News.** "), "news")

    def test_summary_keys(self):
        d = {"generatedAt": "x", "mirrorHead": None, "fetchOk": True, "ghOk": True, "changes": [],
             "entries": [dict(entry("06-things-to-tell-the-user.md", "N"), waitingOn=["read"], waitingWhy="", threadUrl=None, lastChanged=None)]}
        s = serve.make_summary(d)
        self.assertEqual(s["waiting"]["read"], ["06-things-to-tell-the-user.md:n"])
        self.assertIn("answered", s["waiting"])


class StatusNoteTests(unittest.TestCase):
    def test_words_after_colon_are_the_note(self):
        st = lambda t: docsparse.normalize_status(t)[0]
        self.assertEqual(st("added in PR #70: Added a right-click menu (Open, Reload, Copy)"), "done")
        self.assertEqual(st("implemented: x"), "done")
        self.assertEqual(st("skipped in PR #70: needs Windows, still open"), "wontfix")
        self.assertEqual(st("fixed in PR #70: was open"), "fixed")
        self.assertEqual(st("q said: open it again"), "unknown")                   # (a status word only after the ':')
        self.assertEqual(st("partly answered: rest open"), "answered")
        self.assertEqual(st("not a bug: open question"), "wontfix")
        t = "# Bugs\n\n## A\n\n- **One.** Body. _2026-10-24, T, added in PR #70: Open, Reload._\n"
        e = docsparse.parse_file("01-known-bugs.md", t)["entries"][0]
        self.assertEqual(e["status"], "done")
        self.assertEqual([p["code"] for p in docsparse.lint("01-known-bugs.md", t)], ["odd-status"])   # read as done, said once


