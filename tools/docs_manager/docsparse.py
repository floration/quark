#!/usr/bin/env python3
"""Parses the Claude Documents markdown files into entries, and diffs two versions of a file into
entry-level changes (added / edited / status / moved / removed). Pure functions, no I/O, no git.

Entry shape in files 01-08 (README.md of Claude Documents):

    - **Title** (P1-P3 if known, or HALT). Body ... _YYYY-MM-DD, <thread title>, <status>[: note]_

Priority HALT (written `(HALT)` or `(halting)`, any case) ranks above P1: a Claude agent is stopped until q acts.
An entry is *halting* while it is HALT, not finished and not archived (is_halting).

(the date may carry a time, `_2026-10-24 01:12 CT, q, open_`, as in 09-answers-from-q.md).

An entry may wrap over several lines; it ends at a blank line, a heading, the next `- ` bullet, or (once its
trailing italic is seen) the next unindented line, which is then section text. Entries without the italic
get status "unknown". Text after the italic (`_..., done_ Follow-up: ...`) is kept as `tail` and added to the
status note. 00-agent-rules.md, README.md, anything not named NN-*.md, files generated by another tool
(`> Generated by` near the top) and numbered files where hardly any bullet has the italic (a report such as
13-app-audit.md) are documents. lint() lists malformed entries for the page's Problems list.
Python 3 standard library only.
"""
import difflib, re

PARSER_VERSION = 7          # bump when parse/diff output changes: cached diffs are recomputed

STATUSES = ["open", "in-progress", "fixed", "wontfix", "answered", "told", "done"]
DONE_STATUSES = {"fixed", "wontfix", "answered", "told", "done"}
_ALIASES = {"in progress": "in-progress", "inprogress": "in-progress", "won't fix": "wontfix",
            "wont fix": "wontfix", "not a bug": "wontfix", "asked": "open", "waiting": "open",
            "planned": "open", "closed": "done", "shipped": "done", "merged": "done"}

_ENTRY_RE = re.compile(r"^(\s{0,3})[-*]\s+(.*)$")
_HEAD_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_TRAILER_RE = re.compile(r"(?:^|\s)_(\d{4}-\d{2}-\d{2})(?:\s+\d{1,2}:\d{2}(?:\s*[A-Z]{2,4})?)?((?:,[^\n]*?)?)_\s*$")
# the same italic with text after it (it then needs its ', thread, status' part, so a date in the body isn't taken)
_TRAILER_MID_RE = re.compile(r"(?:^|\s)_(\d{4}-\d{2}-\d{2})(?:\s+\d{1,2}:\d{2}(?:\s*[A-Z]{2,4})?)?(,[^\n]*?)_(?=\s+\S)")
_GENERATED_RE = re.compile(r"^>\s*Generated by\b", re.M | re.I)
_PRIO_RE = re.compile(r"\(\s*(P[1-3]|(?i:halt|halting))(?:\s*/\s*(?:P[1-3]|(?i:halt|halting)))?\s*\)")
PRIORITIES = ["HALT", "P1", "P2", "P3"]
PRIORITY_RANK = {p: i for i, p in enumerate(PRIORITIES)}   # HALT first in every sort
_BOLD_RE = re.compile(r"^\*\*(.+?)\*\*(.*)$", re.S)

FILE_KINDS = {  # what one entry of each file is, for change sentences
    "01": "bug", "02": "work item", "03": "possible bug", "04": "performance improvement",
    "05": "possible performance improvement", "06": "note for q", "07": "question for q", "08": "note",
    "09": "answer from q"}


def norm_priority(p):
    """'(halting)' / 'Halt' -> 'HALT'; P1-P3 as written."""
    return "HALT" if p and p.lower() in ("halt", "halting") else p


def is_halting(e):
    """A HALT entry that still stops a Claude agent: not fixed / done / answered / told / wontfix, not archived."""
    return e.get("priority") == "HALT" and e.get("status") not in DONE_STATUSES and not e.get("archived")


def find_trailer(text):
    """The entry's status italic: one ending the text, else the last one with text after it; None if neither."""
    m = _TRAILER_RE.search(text)
    if m: return m
    last = None
    for last in _TRAILER_MID_RE.finditer(text): pass
    return last


def is_generated(text):
    """A file another tool writes (10-github-rules.md, 11-github-notes.md: '> Generated by the GitHub Manager')."""
    return bool(text) and bool(_GENERATED_RE.search(text[:1500]))


def _trailer_share(text):
    """(top-level bullets, how many of them carry a status italic) in a file's text."""
    bullets = with_trailer = 0
    cur = None
    for line in (text or "").replace("\r\n", "\n").split("\n") + [""]:
        e = _ENTRY_RE.match(line)
        if (e and len(e.group(1)) < 2) or not line.strip() or _HEAD_RE.match(line):
            if cur is not None:
                bullets += 1; with_trailer += find_trailer(cur) is not None
            cur = e.group(2) if e and len(e.group(1)) < 2 else None
        elif cur is not None:
            cur += "\n" + line
    return bullets, with_trailer


def file_kind(name, text=None):
    """'entries' for NN-*.md except 00 (rules), else 'document'. With the text: a generated file, or a numbered file
    with 5+ bullets of which under a fifth carry a status italic (a report, not entries), is a document too."""
    m = re.match(r"^(\d\d)-.*\.md$", name)
    if not m or m.group(1) == "00": return "document"
    if text is not None:
        if is_generated(text): return "document"
        bullets, trailers = _trailer_share(text)
        if bullets >= 5 and trailers * 5 < bullets: return "document"
    return "entries"


def slug(text):
    s = re.sub(r"[^a-z0-9]+", "-", (text or "").lower()).strip("-")
    return s[:60].rstrip("-") or "entry"


def normalize_status(text, thread_titles=()):
    """(status, note) from the trailer's status text: first word if it is a known status, else a known
    status word or alias found in the text (note keeps the full text), else 'unknown'."""
    t = (text or "").strip()
    if not t: return "unknown", ""
    low = t.lower()
    for s in STATUSES + ["in progress"]:
        if low == s or re.match(re.escape(s) + r"\b(?![-\w])", low):
            rest = t[len(s):].lstrip(" :,;-").strip()
            return ("in-progress" if s == "in progress" else s), rest
    for a, s in _ALIASES.items():
        if re.match(re.escape(a) + r"\b", low): return s, t
    for s in STATUSES:
        if re.search(r"\b" + re.escape(s) + r"\b", low): return s, t
    for a, s in _ALIASES.items():
        if re.search(r"\b" + re.escape(a) + r"\b", low): return s, t
    return "unknown", t


def parse_trailer(inner, thread_names=()):
    """inner = text after the date inside _..._ (starts with ', ' or empty) -> (thread, status, note, raw)."""
    rest = inner.lstrip(",").strip()
    if not rest: return None, "unknown", "", ""
    thread, stext = None, ""
    low = rest.lower()
    for name in sorted(thread_names, key=len, reverse=True):      # a known thread title may hold commas
        n = name.lower()
        if low == n or low.startswith(n + ","):
            thread, stext = rest[:len(name)], rest[len(name) + 1:].strip()
            break
    if thread is None and re.match(r"(?:%s)\s*:" % "|".join(re.escape(s) for s in STATUSES), low):
        st, note = normalize_status(rest)                           # '_date, answered: yes, both_' (no thread)
        return None, st, note, rest
    if thread is None:
        parts = rest.split(",", 1)
        first = parts[0].strip()
        if len(parts) == 1:
            st, note = normalize_status(first)
            if st != "unknown" and len(first.split()) <= 3: return None, st, note, first
            return first, "unknown", "", ""
        thread, stext = first, parts[1].strip()
    st, note = normalize_status(stext)
    return thread, st, note, stext


def _split_title(text):
    """'**Title** (P2). Body' -> (title, priority, body). Without bold, the first sentence is the title."""
    m = _BOLD_RE.match(text)
    prio = None
    if m:
        title, body = m.group(1).strip(), m.group(2)
        pm = _PRIO_RE.search(title)
        if pm:
            prio = pm.group(1)
            title = (title[:pm.start()] + title[pm.end():]).strip()
            title = re.sub(r"\s+([.,:;])", r"\1", title)
        pm = re.match(r"\s*" + _PRIO_RE.pattern + r"\s*([.,:;])?", body)
        if pm:
            prio = prio or pm.group(1)
            body = body[pm.end():]
        body = re.sub(r"^\s*[;:,.]\s*", "", body).strip()      # '**Title**: body' / '**Title**; body' 
    else:
        sm = re.match(r"(.{8,}?[.:!?])(\s|$)", text)
        title = sm.group(1) if sm and len(sm.group(1)) <= 120 else text[:80].rstrip() + ("..." if len(text) > 80 else "")
        body = text[len(sm.group(1)):].strip() if sm and len(sm.group(1)) <= 120 else text
    if not prio:
        pm = _PRIO_RE.search(re.sub(r"`[^`\n]*`", lambda m: " " * len(m.group(0)), body))   # not '`(HALT)`' quoted in text
        if pm: prio = pm.group(1)
    return title, norm_priority(prio), body


def parse_file(name, text, thread_names=()):
    """-> {"title", "kind", "sections": [...], "notes": [{"section", "text"}], "entries": [...]}.
    Entry: id, file, section, title, priority, body, date, thread, status, statusNote, statusText, line, endLine
    (1-based first and last line of the entry)."""
    lines = (text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    kind = file_kind(name, text or "")
    out = {"title": "", "kind": kind, "generated": is_generated(text or ""), "sections": [], "notes": [], "entries": []}
    section, cur, closed, note = "", None, False, None

    def finish():
        nonlocal cur
        if cur is not None: out["entries"].append(_make_entry(name, section_of[0], cur, thread_names))
        cur = None

    def flush_note():
        nonlocal note
        if note and note["text"].strip(): out["notes"].append(note)
        note = None

    section_of = [""]
    for i, line in enumerate(lines, 1):
        h = _HEAD_RE.match(line)
        if h:
            finish(); flush_note()
            if len(h.group(1)) == 1 and not out["title"]:
                out["title"] = h.group(2)
            else:
                section = h.group(2)
                if section not in out["sections"]: out["sections"].append(section)
            section_of[0] = section
            continue
        if kind != "entries": continue
        e = _ENTRY_RE.match(line)
        if e and (len(e.group(1)) < 2 or cur is None):           # deeper bullets belong to the entry above
            finish(); flush_note()
            cur = {"lines": [e.group(2)], "line": i, "end": i}
            closed = find_trailer(e.group(2)) is not None
            continue
        if not line.strip():
            finish(); closed = False
            if note: note["text"] += "\n"
            continue
        indented = line[:1] in (" ", "\t")
        if cur is not None and (indented or not closed):
            cur["lines"].append(("  " + line.strip()) if e else line.strip())
            cur["end"] = i
            closed = closed or find_trailer(line) is not None
            continue
        finish()
        if note is None: note = {"section": section, "text": line.strip()}
        else: note["text"] = (note["text"].rstrip("\n") + ("\n\n" if note["text"].endswith("\n") else "\n") + line.strip())
    finish(); flush_note()
    if out["entries"] and any(en["section"] == "" for en in out["entries"]) and "" not in out["sections"]:
        out["sections"].insert(0, "")
    seen = {}
    for en in out["entries"]:
        n = seen.get(en["id"], 0) + 1
        seen[en["id"]] = n
        if n > 1: en["id"] += "#%d" % n
    return out


def _make_entry(name, section, cur, thread_names):
    text = "\n".join(cur["lines"]).strip()
    date = thread = None
    status, note, stext, tail, trailer = "unknown", "", "", "", False
    m = find_trailer(text)
    if m:
        date, trailer = m.group(1), True
        thread, status, note, stext = parse_trailer(m.group(2), thread_names)
        tail = re.sub(r"\s+", " ", text[m.end():]).strip()
        if tail: note = "%s; %s" % (note, tail) if note else tail
        text = text[:m.start()].rstrip()
    title, prio, body = _split_title(text)
    return {"id": "%s:%s" % (name, slug(title)), "file": name, "section": section, "title": title,
            "priority": prio, "body": body, "date": date, "thread": thread, "status": status,
            "statusNote": note, "statusText": stext, "archived": section.strip().lower() == "archive",
            "line": cur["line"], "endLine": cur["end"], "tail": tail, "hasTrailer": trailer,
            "boldTitle": "ok" if _BOLD_RE.match(text) else "unclosed" if text.lstrip().startswith("**") else "none"}


# ---- lint: malformed entries, for the page's Problems list ---------------------------------------------------

_STATUS_WORD_RE = re.compile(r"(?:%s)\b(?![-\w])" % "|".join(re.escape(x) for x in STATUSES + ["in progress"]), re.I)
SEVERITIES = ("error", "warn", "info")


def lint(name, text, parsed=None, thread_names=()):
    """Problems in one file, in line order: [{file, line, severity (error / warn / info), code, message, entryId,
    title}]. Errors break the parse (a heading split out of an entry, an unclosed **title**); warnings make an
    entry read wrong (no status line, a status outside the word list, sections below Archive, the same title twice);
    info is style (no thread, text after the status line, an open item in Archive, no bold title). 08 (reference
    notes) is not checked for status or thread."""
    p = parsed or parse_file(name, text, thread_names)
    out = []

    def add(line, sev, code, msg, e=None):
        out.append({"file": name, "line": line, "severity": sev, "code": code, "message": msg,
                    "entryId": e["id"] if e else None, "title": e["title"] if e else None})

    m = re.match(r"^(\d\d)-", name)
    if p["kind"] != "entries":
        if m and m.group(1) != "00" and not p.get("generated"):
            bullets, trailers = _trailer_share(text)
            if bullets: add(1, "info", "read-as-document", "Shown as a document, not as entries: only %d of its %d bullets end "
                                                           "with a _date, thread, status_ line." % (trailers, bullets))
        return out
    lines = (text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n")
    heads, archive_at = [], None
    for i, line in enumerate(lines, 1):
        h = _HEAD_RE.match(line)
        if not h or len(h.group(1)) == 1: continue
        t = h.group(2)
        if find_trailer(t) or t.count("**") % 2 or t.count("`") % 2:
            add(i, "error", "heading-in-entry", "This line starts with ## inside an entry, so it is read as a heading (\"%s\") and "
                "cuts the entry above it short. Join it back onto the entry's line." % _short(t)[:70])
            continue
        heads.append((i, t))
        if t.strip().lower() == "archive" and archive_at is None: archive_at = i
    if archive_at is not None:
        for i, t in heads:
            n = sum(1 for e in p["entries"] if e["section"] == t)
            if i > archive_at and n:
                add(i, "warn", "after-archive", "Section \"%s\" (%d %s) sits below ## Archive, which goes at the bottom (README "
                    "rule 4): readers stop at Archive. Move the section above it." % (_short(t)[:60], n, "entry" if n == 1 else "entries"))
    notes = name.startswith("08")
    first_of = {}
    for e in p["entries"]:
        base = e["id"].split("#", 1)[0]
        if e["boldTitle"] == "unclosed":
            add(e["line"], "error", "unclosed-title", "The title's ** is never closed, so the title and text run together "
                "(the rest of the entry may have been split off below).", e)
        elif e["boldTitle"] == "none":
            add(e["line"], "info", "no-title", "No **bold title**: the first sentence is used as the title.", e)
        if base in first_of:
            add(e["line"], "warn", "duplicate-title", "Same title as the entry on line %d; links and history may mix them up." % first_of[base], e)
        else: first_of[base] = e["line"]
        if not notes:
            if not e["hasTrailer"]:
                add(e["endLine"], "warn", "no-status", "No _date, thread, status_ line at the end, so it shows as \"No status\".", e)
            elif e["status"] == "unknown":
                add(e["endLine"], "warn", "bad-status", "The status \"%s\" isn't a status word (%s), so it shows as \"No status\"."
                    % (_short(e["statusText"] or "(none)")[:40], ", ".join(STATUSES)), e)
            elif e["statusText"] and not _STATUS_WORD_RE.match(e["statusText"].strip()):
                add(e["endLine"], "info", "odd-status", "The status \"%s\" isn't one of the status words; it is read as %s."
                    % (_short(e["statusText"])[:40], e["status"]), e)
            if e["hasTrailer"] and not e["thread"]:
                add(e["endLine"], "info", "no-thread", "No thread in the status line (_date, <thread title>, status_).", e)
        if e["tail"]:
            add(e["endLine"], "info", "text-after-status", "Text after the status line (\"%s\") is read as part of the status note; "
                "move it before the _date, thread, status_." % _short(e["tail"])[:60], e)
        if e["archived"] and e["status"] in ("open", "in-progress") and not notes:
            add(e["line"], "info", "open-in-archive", "Still %s but in Archive: finish it or move it above Archive." % e["status"], e)
    out.sort(key=lambda x: (x["line"], SEVERITIES.index(x["severity"])))
    return out


# ---- diff -------------------------------------------------------------------------------------------------

def _ratio(a, b):
    if not a and not b: return 1.0
    sm = difflib.SequenceMatcher(None, a or "", b or "", autojunk=False)
    if sm.real_quick_ratio() < 0.3 or sm.quick_ratio() < 0.3: return 0.0
    return sm.ratio()


def _words(t):
    return set(re.findall(r"[a-z0-9]+", (t or "").lower()))


def _similar(a, b):
    """0..1 how likely b is an edited a (title mostly, body as backup)."""
    ta, tb = a["title"], b["title"]
    tr = _ratio(ta.lower(), tb.lower())
    wa, wb = _words(ta), _words(tb)
    contain = 0.0
    if wa and wb and (wa <= wb or wb <= wa): contain = 0.6 + 0.3 * min(len(wa), len(wb)) / max(len(wa), len(wb))
    br = _ratio(a["body"][:600], b["body"][:600])
    return max(tr, contain, 0.45 * tr + 0.55 * br, br if br > 0.85 else 0.0)


def _pair(old, new, threshold):
    """Greedy best-first pairing of two entry lists by similarity -> [(o, n)], leftovers."""
    cands = []
    for i, o in enumerate(old):
        for j, n in enumerate(new):
            s = _similar(o, n)
            if s >= threshold: cands.append((s, i, j))
    cands.sort(key=lambda c: (-c[0], c[1], c[2]))
    used_o, used_n, pairs = set(), set(), []
    for s, i, j in cands:
        if i in used_o or j in used_n: continue
        used_o.add(i); used_n.add(j); pairs.append((old[i], new[j]))
    return pairs, [o for i, o in enumerate(old) if i not in used_o], [n for j, n in enumerate(new) if j not in used_n]


def _short(title):
    return (title or "").rstrip(" .:,;")


HALT_ON, HALT_OFF = "Now halting a Claude agent", "No longer halting"


def _halt_item(item, o, n):
    """Mark an item where the entry starts or stops halting: 'Now halting a Claude agent: <title> (<what>)' /
    'No longer halting: ...', with halting: True / False. Items that don't change it are returned as they are."""
    was, now = bool(o and is_halting(o)), bool(n and is_halting(n))
    if was == now: return item
    e = n or o
    t = _short(e["title"])
    rest = item["summary"][len(t) + 2:] if item["summary"].startswith(t + ": ") else item["summary"]
    if item["kind"] == "added": rest = "new " + FILE_KINDS.get(e["file"][:2], "entry")
    item["summary"] = "%s: %s%s" % (HALT_ON if now else HALT_OFF, t, " (%s)" % rest if rest and rest != t else "")
    item["what"] = ("now halting a Claude agent" if now else "no longer halting") + (" (%s)" % rest if rest and rest != t else "")
    item["halting"] = now
    return item


def _added_summary(e):
    k = FILE_KINDS.get(e["file"][:2], "entry")
    t = _short(e["title"])
    if e["file"].startswith("02"):
        return ("Work claimed: %s" if e["status"] == "in-progress" else
                "Planned: %s" if e["status"] in ("open", "unknown") else "Work recorded as %s: %%s" % e["status"]) % t
    return "New %s: %s" % (k, t) + ("" if e["status"] in ("open", "unknown", "in-progress") else " (%s)" % e["status"])


def _item(kind, e, summary, **extra):
    """One change item; 'what' is the summary without the leading '<title>: ' (for 'last changed: ...')."""
    t = _short(e["title"]) + ": "
    it = {"entryId": e["id"], "file": e["file"], "title": e["title"], "kind": kind, "from": None, "to": None,
          "summary": summary, "what": summary[len(t):] if kind != "added" and summary.startswith(t) else kind,
          "section": e["section"]}
    it.update(extra)
    return it


def _compare(o, n):
    """One item for a matched pair, or None when nothing a reader cares about changed."""
    t = _short(n["title"])
    extra = {}
    if o["id"] != n["id"]: extra["fromId"] = o["id"]
    if o["file"] != n["file"]: extra["fromFile"] = o["file"]
    moved_sec = o["section"] != n["section"]
    if moved_sec: extra.update(fromSection=o["section"], toSection=n["section"])
    if o["status"] != n["status"]:
        s = "%s: %s -> %s" % (t, o["status"], n["status"])
        if n["statusNote"] and n["statusNote"] != o["statusNote"]: s += " (%s)" % n["statusNote"]
        if moved_sec: s += ", moved to %s" % (n["section"] or "the top")
        return _item("status", n, s, **dict(extra, **{"from": o["status"], "to": n["status"]}))
    if o["file"] != n["file"]:
        return _item("moved", n, "%s: moved from %s to %s" % (t, o["file"], n["file"]),
                     **dict(extra, **{"from": o["file"], "to": n["file"]}))
    what = []
    if o["title"] != n["title"]: what.append("title was \"%s\"" % _short(o["title"]))
    if o["priority"] != n["priority"]: what.append("priority %s -> %s" % (o["priority"] or "none", n["priority"] or "none"))
    if o["statusNote"] != n["statusNote"]: what.append("status note now \"%s\"" % n["statusNote"] if n["statusNote"] else "status note removed")
    if o["body"] != n["body"]: what.append("text edited")
    if o["thread"] != n["thread"]: what.append("thread %s -> %s" % (o["thread"], n["thread"]))
    if o["date"] != n["date"]: what.append("date %s -> %s" % (o["date"], n["date"]))
    if moved_sec and not what:
        return _item("moved", n, "%s: moved from %s to %s" % (t, o["section"] or "the top", n["section"] or "the top"),
                     **dict(extra, **{"from": o["section"], "to": n["section"]}))
    if not what: return None
    if moved_sec: what.append("moved to %s" % (n["section"] or "the top"))
    ex = dict(extra)
    if o["title"] != n["title"]: ex.update({"from": o["title"], "to": n["title"]})
    return _item("edited", n, "%s: %s" % (t, ", ".join(what)), **ex)


def diff_entries(old_entries, new_entries):
    """Entry-level changes between two lists of entries (any files). Matching: same id, then fuzzy title within
    the same file, then (moves) fuzzy title/body across files."""
    items = []
    old_by = {e["id"]: e for e in old_entries}
    new_by = {e["id"]: e for e in new_entries}
    pairs = [(old_by[i], new_by[i]) for i in new_by if i in old_by]
    lo = [e for e in old_entries if e["id"] not in new_by]
    ln = [e for e in new_entries if e["id"] not in old_by]
    for f in sorted({e["file"] for e in lo} & {e["file"] for e in ln}):
        p, ro, rn = _pair([e for e in lo if e["file"] == f], [e for e in ln if e["file"] == f], 0.6)
        pairs += p
        lo = [e for e in lo if e["file"] != f] + ro
        ln = [e for e in ln if e["file"] != f] + rn
    p, lo, ln = _pair(lo, ln, 0.85)
    pairs += [(o, n) for o, n in p if o["file"] != n["file"]] + [(o, n) for o, n in p if o["file"] == n["file"]]
    for o, n in pairs:
        it = _compare(o, n)
        if it: items.append(_halt_item(it, o, n))
    for n in ln: items.append(_halt_item(_item("added", n, _added_summary(n), to=n["status"]), None, n))
    for o in lo: items.append(_halt_item(_item("removed", o, "%s: removed from %s" % (_short(o["title"]), o["file"]), **{"from": o["status"]}), o, None))
    order = {e["id"]: i for i, e in enumerate(new_entries)}
    items.sort(key=lambda it: (it["file"], order.get(it["entryId"], 1 << 30)))
    return items


def diff_document(name, old_text, new_text, title=None):
    """One 'edited' item for a document file (rules, README): how many lines changed."""
    a = (old_text or "").replace("\r\n", "\n").splitlines()
    b = (new_text or "").replace("\r\n", "\n").splitlines()
    if a == b: return []
    plus = minus = 0
    for line in difflib.unified_diff(a, b, lineterm="", n=0):
        if line.startswith("+") and not line.startswith("+++"): plus += 1
        elif line.startswith("-") and not line.startswith("---"): minus += 1
    t = title or name
    kind = "added" if not a else "removed" if not b else "edited"
    word = {"added": "added", "removed": "removed", "edited": "edited"}[kind]
    return [{"entryId": None, "file": name, "title": t, "kind": kind, "from": None, "to": None,
             "summary": "%s %s (+%d / -%d lines)" % (t, word, plus, minus),
             "what": "%s (+%d / -%d lines)" % (word, plus, minus), "section": None}]
