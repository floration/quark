/* Files tab: each file as a readable document (or raw text), with last change and PC-sync badges, an outline on
   wide screens, and the Problems list (malformed entries the server's lint found; a count on the tab). */
'use strict';
(function (DM) {
  const {h, clear, $} = DM;
  const st = DM.state;
  const PROBLEMS = '__problems';
  const SEV = {error: {label: 'Error', cls: 'err'}, warn: {label: 'Warning', cls: 'warn'}, info: {label: 'Style', cls: 'info'}};
  const GHM_EDITOR = 'http://127.0.0.1:8767/#tab=editor';
  let jump = null;   // {file, line}: scroll the readable file to this source line after the next render
  // Rendered files, kept per file and view (readable / raw) until their text changes: switching back to a file moves
  // its nodes back instead of rendering the markdown again (13-app-audit.md took 0.4-0.7 s each time).
  const docCache = new Map();   // name + '|r' / '|m' -> {md, nodes}
  const PROB_PAGE = 150;        // Problems rows rendered at once ("Show more" for the rest)
  let probLimit = PROB_PAGE;
  function plural(n, one, many) { return n + ' ' + (n === 1 ? one : many); }
  // A file's problem count, said the same way in the list and in its toolbar: what to fix, then style notes.
  function probWords(fp) {
    const nb = bad(fp).length, ns = fp.length - nb;
    return [nb ? plural(nb, 'problem', 'problems') : '', ns ? plural(ns, 'style note', 'style notes') : ''].filter(Boolean).join(' + ');
  }

  function problems() { return st.data && Array.isArray(st.data.problems) ? st.data.problems : []; }
  function bad(list) { return list.filter(p => p.severity !== 'info'); }

  // The count on the Files tab: errors and warnings (style notes don't count).
  function badge() {
    const b = $('#tabs button[data-tab="files"]');
    if (!b) return;
    let el = b.querySelector('.tab-badge');
    const n = bad(problems()).length, errs = problems().filter(p => p.severity === 'error').length;
    if (!n) { if (el) el.remove(); return; }
    if (!el) { el = h('span', {class: 'tab-badge'}); b.appendChild(el); }
    el.textContent = String(n);
    el.classList.toggle('err', errs > 0);
    el.title = n + (n === 1 ? ' problem' : ' problems') + ' in the files (' + errs + ' that break an entry): Files › Problems';
  }

  function listItem(key, on, kids, onclick) {
    return h('div', {class: 'list-item' + (on ? ' on' : ''), tabindex: 0, role: 'button', dataset: {file: key}, onclick,
      onkeydown: ev => { if (ev.key === 'Enter' || ev.key === ' ') { ev.preventDefault(); ev.currentTarget.click(); } }}, kids);
  }

  function render() {
    const d = st.data, p = st.prefs.files;
    if (!d.files.length) { clear($('#fBody')).append(h('div', {class: 'empty'}, 'No files.')); return; }
    if (p.sel !== PROBLEMS && !d.files.some(f => f.name === p.sel)) p.sel = (d.files.find(f => f.name.startsWith('07')) || d.files[0]).name;
    const probs = problems();
    const byFile = {};
    for (const x of probs) (byFile[x.file] = byFile[x.file] || []).push(x);
    // counts per file in one pass
    const cnt = {};
    for (const e of d.entries) {
      const c = cnt[e.file] || (cnt[e.file] = {n: 0, open: 0, q: 0});
      c.n++; if (DM.isOpen(e)) c.open++; if (DM.needsQ(e)) c.q++;
    }
    const list = clear($('#fList'));
    const nb = bad(probs).length;
    list.appendChild(listItem(PROBLEMS, p.sel === PROBLEMS, [
      h('div', {class: 't'}, 'Problems', nb ? h('span', {class: 'badge probn' + (probs.some(x => x.severity === 'error') ? ' err' : '')}, String(nb)) : null),
      h('div', {class: 'd'}, probs.length ? nb + ' to fix, ' + (probs.length - nb) + ' style notes' : 'every entry reads cleanly')],
      () => { probLimit = PROB_PAGE; DM.app.openFile(PROBLEMS); $('#fScroll').scrollTop = 0; }));
    for (const f of d.files) {
      const c = cnt[f.name] || {n: 0, open: 0, q: 0};
      const fp = byFile[f.name] || [], fb = bad(fp).length;
      list.appendChild(listItem(f.name, f.name === p.sel, [
        h('div', {class: 't'}, DM.fileTitle(f.name), f.pcUnsynced ? h('span', {class: 'badge pc', title: 'Edited on the PC, not synced yet'}, 'PC') : null,
          f.generated ? h('span', {class: 'badge arch', title: 'Generated by the GitHub Manager; edit it there'}, 'generated') : null),
        h('div', {class: 'd'}, f.kind === 'document' ? 'document' : c.n + ' entries' + (c.open ? ', ' + c.open + ' open' : ''),
          c.q ? h('span', {class: 'nqc', title: c.q + ' waiting on q'}, ' · ' + c.q + ' for q') : null,
          fb ? h('span', {class: 'probc', title: probWords(fp) + ' in this file (Files › Problems); style notes aren’t counted here'}, ' · ' + plural(fb, 'problem', 'problems')) : null),
        f.lastChange && f.lastChange.time ? h('div', {class: 'd'}, 'changed ', DM.timeEl(f.lastChange.time)) : null],
        () => { DM.app.openFile(f.name); $('#fScroll').scrollTop = 0; }));
    }
    if (p.sel === PROBLEMS) return renderProblems(probs);
    const f = d.files.find(x => x.name === p.sel);
    const canEditFile = DM.edit && DM.edit.canEdit() && !f.generated;
    const fp = byFile[f.name] || [];
    DM.append(clear($('#fBar')), [h('b', {class: 'f-title'}, DM.fileTitle(f.name)), h('code', null, f.name),
      f.pcUnsynced ? h('span', {class: 'pill q sm', title: 'The copy on the PC has edits that are not on GitHub yet'}, 'Edited on the PC, not synced') : null,
      f.generated ? h('span', {class: 'pill sm nobody', title: 'Another tool writes this file; edits made here would be overwritten'}, 'Generated: ',
        DM.ext(GHM_EDITOR, 'edit it in the GitHub Manager', null, 'The GitHub Manager’s Editor tab')) : null,
      fp.length ? h('button', {class: 'mini', title: 'This file’s entries that don’t read cleanly (problems = errors and warnings, as in the list)', onclick: () => DM.app.openFile(PROBLEMS)},
        probWords(fp)) : null,
      f.lastChange && f.lastChange.time ? h('span', {class: 'dim'}, 'Last changed ', DM.timeEl(f.lastChange.time, 'dayclock'), ' (', DM.timeEl(f.lastChange.time), ')',
        f.lastChange.subject ? h('span', {class: 'faint'}, ': ' + f.lastChange.subject) : null) : null,
      h('span', {class: 'spacer'}),
      canEditFile ? h('button', {class: 'mini', title: 'Open this file in the Edit tab', onclick: () => DM.edit.openAt(f.name, 1)}, 'Edit this file') : null,
      h('div', {class: 'seg'},
        h('button', {class: p.raw ? '' : 'on', onclick: () => { p.raw = false; DM.app.save(); render(); }}, 'Readable'),
        h('button', {class: p.raw ? 'on' : '', onclick: () => { p.raw = true; DM.app.save(); render(); }}, 'Raw text'))]);
    const body = $('#fBody');
    body.className = 'doc md' + (p.raw ? ' raw' : '') + ((f.markdown || '').length > 40000 ? ' long' : '');
    const toc = clear($('#fToc'));
    const key = f.name + (p.raw ? '|r' : '|m'), md = f.markdown || '', hit = docCache.get(key);
    if (hit && hit.md === md) body.replaceChildren(...hit.nodes);
    else {
      clear(body);
      if (p.raw) body.appendChild(h('pre', {class: 'rawtext'}, numbered(md)));
      else DM.md.into(body, md, false, {lines: true});
      docCache.set(key, {md, nodes: [...body.childNodes]});
      for (const k of docCache.keys()) if (!st.fileByName[k.split('|')[0]]) docCache.delete(k);
    }
    // outline (wide screens): the file's sections, click to jump
    const heads = p.raw ? [] : [...body.querySelectorAll('h2, h3')];
    toc.hidden = heads.length < 3;
    if (heads.length >= 3) {
      toc.appendChild(h('div', {class: 'toc-h'}, 'Sections'));
      for (const el of heads) toc.appendChild(h('a', {class: 'toc-i ' + el.tagName.toLowerCase(), href: '#file=' + encodeURIComponent(f.name),
        onclick: ev => { ev.preventDefault(); el.scrollIntoView({block: 'start'}); }}, el.textContent));
    }
    if (jump && jump.file === f.name) { const j = jump; jump = null; requestAnimationFrame(() => showLine(body, j.line)); }
  }
  // Raw text with line numbers, so a problem's "line 51" can be found.
  function numbered(text) {
    const lines = text.split('\n'), w = String(lines.length).length;
    return lines.map((l, i) => h('span', {class: 'rl', dataset: {l: i + 1}}, h('i', {class: 'ln'}, String(i + 1).padStart(w)), l + '\n'));
  }
  function showLine(body, line) {
    let best = null;
    for (const el of body.querySelectorAll('[data-l]')) { if (+el.dataset.l <= line) best = el; else break; }
    if (!best) return;
    best.scrollIntoView({block: 'center'});
    best.classList.remove('line-hit'); void best.offsetWidth; best.classList.add('line-hit');
  }

  function renderProblems(probs) {
    const p = st.prefs.files, all = p.probAll !== false;
    const shown = all ? probs : bad(probs);
    DM.append(clear($('#fBar')), [h('b', {class: 'f-title'}, 'Problems'),
      h('span', {class: 'dim'}, bad(probs).length + ' to fix · ' + (probs.length - bad(probs).length) + ' style notes'),
      h('span', {class: 'spacer'}),
      h('div', {class: 'seg'},
        h('button', {class: all ? 'on' : '', onclick: () => { p.probAll = true; DM.app.save(); render(); }}, 'All'),
        h('button', {class: all ? '' : 'on', onclick: () => { p.probAll = false; DM.app.save(); render(); }}, 'Errors and warnings'))]);
    clear($('#fToc')).hidden = true;
    const body = clear($('#fBody'));
    body.className = 'doc probs';
    body.appendChild(h('p', {class: 'faint'}, 'Entries the manager can’t read the way they were meant: errors break an entry (a heading split out of it, a title never closed), ',
      'warnings make it show wrong (no status line, a status outside the word list, sections below Archive), style notes are small. ',
      'Line numbers are the file’s own. Fixing one here or in the docs repo clears it on the next refresh.'));
    if (!shown.length) { body.appendChild(h('div', {class: 'empty ok'}, probs.length ? 'No errors or warnings; only style notes.' : 'No problems: every entry reads cleanly.')); return; }
    const page = shown.slice(0, probLimit);
    const files = [...new Set(page.map(x => x.file))];
    for (const name of files) {
      const fp = page.filter(x => x.file === name);
      body.appendChild(h('h3', {class: 'prob-f'}, h('a', {href: '#file=' + encodeURIComponent(name), onclick: ev => { ev.preventDefault(); DM.app.openFile(name); }}, DM.fileTitle(name)),
        ' ', h('code', null, name), h('span', {class: 'faint'}, ' · ' + fp.length)));
      body.appendChild(h('ul', {class: 'prob-list'}, fp.map(x => {
        const sv = SEV[x.severity] || SEV.info, e = x.entryId && st.entryById[x.entryId];
        return h('li', {class: 'prob ' + sv.cls},
          h('span', {class: 'prob-sev'}, sv.label),
          h('span', {class: 'prob-ln'}, 'line ' + x.line),
          h('div', {class: 'prob-b'},
            e ? h('a', {class: 'prob-t', href: '#entry=' + encodeURIComponent(e.id), onclick: ev => { ev.preventDefault(); DM.app.openEntry(e.id); }}, DM.md.into(h('span'), DM.trimTitle(e.title), true)) :
              x.title ? h('span', {class: 'prob-t'}, DM.trimTitle(x.title)) : null,
            h('div', {class: 'prob-m'}, x.message)),
          h('span', {class: 'prob-act'},
            h('button', {class: 'mini', title: 'Show this line in the file', onclick: () => { jump = {file: name, line: x.line}; st.prefs.files.raw = false; DM.app.openFile(name); }}, 'Show'),
            DM.edit && DM.edit.canEdit() && !(st.fileByName[name] || {}).generated ?
              h('button', {class: 'mini', title: 'Open the file in the Edit tab at this line', onclick: () => DM.edit.openAt(name, x.line, e ? e.title : null)}, 'Edit') : null,
            DM.edit ? DM.edit.fixButton(x) : null));
      })));
    }
    if (shown.length > page.length) body.appendChild(h('button', {class: 'more-btn', onclick: () => { probLimit += 300; render(); }},
      'Show more (' + (shown.length - page.length) + ' left)'));
  }

  (DM.views = DM.views || {}).files = {render, scroller: () => $('#fScroll')};
  DM.files = {badge, PROBLEMS};
})(window.DM);
